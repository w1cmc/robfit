      SUBROUTINE FROMSP(NADAT,ILDAT)
      IMPLICIT REAL*8 (A-H,O-Z)
      CHARACTER*256 NADAT
      CHARACTER*80 CTEMP
      DIMENSION DAT(:),IDAT(:)
      ALLOCATABLE DAT,IDAT
      LOGICAL LEGY,LRES,LEFF,LATT,LSKEW,LESCAPE,LCAS,LRAN,LPCAP
      COMMON /FITTEDCONS/EgyCal(6),ResCal(6),FITEFF(6),SKEW(6,3),
     2 ATTNEX(8,3),ESCAPE(3),THETACAS,TRAN,PCAP,LEGY(6),LRES(6),
     3 LEFF(6),LSKEW(6,3),LATT(8,3),LESCAPE(3),LCAS,LRAN,LPCAP
      COMMON /INTVALS/IBEGC,IENDC,IDUM(20)
      OPEN(2,FILE=NADAT(:ILDAT))
      DO I=1,3
        READ(2,'(A80)')CTEMP
      ENDDO
      READ(2,'(A)')CTEMP 
      IF(CTEMP(:19).EQ.'Energy calibration:')THEN
        READ(CTEMP(20:),*)(EGYCAL(I),I=1,6)
      ENDIF  
      READ(2,'(A20)')CTEMP
      READ(CTEMP(6:),*)IENDC
      ALLOCATE (DAT(IENDC))
      IF(CTEMP(:4).EQ.'FREE'.OR.CTEMP(:4).EQ.'REAL')THEN
        READ(2,*)(DAT(I),I=1,IENDC) 
      ELSEIF(CTEMP(:4).EQ.'Z4DA'.OR.CTEMP(:4).EQ.'HDAT')THEN
        ALLOCATE (IDAT(IENDC))
        IF(CTEMP(:4).EQ.'Z4DA')THEN
          READ(2,'(20Z4)')(IDAT(I),I=1,IENDC)
        ELSE
          READ(2,'(10Z8)')(IDAT(I),I=1,IENDC)
        ENDIF    
        DO I=1,IENDC
          DAT(I)=IDAT(I)
        ENDDO
        DEALLOCATE(IDAT)
      ENDIF
      CLOSE(2) 
      IBEGC=1
      CTEMP=NADAT(:ILDAT-3)//'dat.unf'
      OPEN(2,FILE=CTEMP,FORM='UNFORMATTED')
      WRITE(2)IENDC
      WRITE(2)(REAL(DAT(I),4),I=1,IENDC)
      CLOSE(2)
      DEALLOCATE(DAT)
      RETURN
      END        

