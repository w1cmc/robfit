      FUNCTION BNRAPH(BEGC,ENDC,ALAMDA,LBRACK,ROBMFU)
C BNRAPH IS RETURNED AS THE SMALLEST VALUE OF ROBMFU(ALAMBDA)   
C BRACK BEGINS WITH X1=ALAMBDA AND F1 = F(ALAMDA)
C IT RETURNS .TRUE. X2 AND F2(X2) SUCH THAT F1*F2 <= 0 
C OR .FALSE.  X2 AND F2 SUCH THAT ABS(F2(X2)) IS SMALLEST VALUE FOUND  
C IN THE RANGE X2 = EXP(-BEGC) TO EXP(ENDC)  
C IF(BRACK) FNRAF RETURNS X2 AND THE SMALLEST VALUE OF ABS(ROBMFU(X2))
      IMPLICIT REAL*8 (A-H,O-Z)
      LOGICAL LBRACK,BRACK
      COMMON /PASS/NW17,NW18,NCONP,NCOND,FRP,CHIP,AJP     
      DATA FACT1,FACT2/1.377D0,1.0377D0/,NTRY/16/
      EXTERNAL ROBMFU
      X1=ALAMDA
      F1=ROBMFU(X1)
      LBRACK=BRACK(FACT1,NTRY,BEGC,ENDC,X1,X2,F1,F2,ROBMFU)
      IF(LBRACK)THEN
        BNRAPH=FNRAF(X1,F1,X2,F2,ROBMFU)
        ALAMDA=X2
      ELSE
        LBRACK=BRACK(FACT2,NTRY,BEGC,ENDC,X1,X2,F1,F2,ROBMFU)
        IF(LBRACK)THEN
          BNRAPH=FNRAF(X1,F1,X2,F2,ROBMFU)
          ALAMDA=X2
        ELSE
          BNRAPH=F1
          ALAMDA=X1 
        ENDIF    
      ENDIF
      RETURN
      END  

      LOGICAL FUNCTION BRACK(FACT,NTRY,BEGC,ENDC,X1,X2,F1,F2,ROBMFU)
C ON ENTRY F1=FUN(X1)
C ON TRUE EXIT X1 IS CLOSEST POINT TO X2,
C  F1=ROBMIN(X1); F2=ROBMIN(X2) AND F1*F2 < 0  
C ON FALSE EXIT X1 AND F1 ARE UNCHANGED FROM ENTRY X2 AND F2 ARE
C  LAST UP POINTS.
      IMPLICIT REAL*8 (A-H,O-Z)
      COMMON /PASS/NW17,NW18,NCONP,NCOND,FRP,CHIP,AJP 
      POW=FACT**NTRY
      X1B=X1 
      DUP=(ENDC-X1B)/POW
      DDOWN=(X1B-BEGC)/POW
      FMULT=FACT  
      X1D=X1
      F1D=F1
      X1U=X1
      F1U=F1
      BRACK=.TRUE.  
      DO I=1,NTRY
        XT=X1B-DDOWN*FMULT !go down
        FT=ROBMFU(XT) 
        IF(FT*F1.LE.0D0)THEN
          X2=XT
          F2=FT
          X1=X1D
          F1=F1D
          RETURN
        ELSE          
          X1D=XT
          F1D=FT
        ENDIF  
        XT=X1B+DUP*FMULT !go up
        FT=ROBMFU(XT)
        IF(FT*F1.LE.0D0)THEN
          X2=XT
          F2=FT
          X1=X1U
          F1=F1U
          RETURN
        ELSE          
          X1U=XT
          F1U=FT 
        ENDIF  
        FMULT=FMULT*FACT
      ENDDO
      BRACK=.FALSE.
      RETURN
      END

      FUNCTION FNRAF(X1,F1,X2,F2,ROBMFU)
C FNRAF IS RETURNED AS THE SMALLEST VALUE FOUND
C X1 AND X2 ARE RETURNED AS CLOSE TOGETHER AS POSSIBLE 
C ON ENTRY F1=ROBMFU(X1), F2=ROBMFU(X2) NORMALLY FOUND IN BRACK           
      IMPLICIT REAL*8 (A-H,O-Z)
      DO NCALL=1,500
        IF(NCALL.EQ.10*(NCALL/10).OR.NCALL.LT.10)THEN
          X=(X1+X2)/2
        ELSE
          IF(F2.EQ.F1)THEN
            X=X1
          ELSE  
            X=X1-F1*(X2-X1)/(F2-F1)
          ENDIF  
          IF(X.GE.MAX(X1,X2))X=(X1+X2)/2
          IF(X.LE.MIN(X1,X2))X=(X1+X2)/2
        ENDIF
        FT=ROBMFU(X)
        IF(FT*F1.GT.0D0)THEN
          X1=X
          F1=FT
        ELSE
          X2=X
          F2=FT  
        ENDIF
        IF(ABS(X1-X2)/MAX(ABS(X1),ABS(X2)).LT.1D-15)THEN
          FNRAF=MIN(F1,F2)
          RETURN
        ENDIF  
      ENDDO
      FNRAF=MIN(F1,F2)
      RETURN
      END

