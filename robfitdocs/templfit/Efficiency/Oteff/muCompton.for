      FUNCTION EFCOMPT(EGY)
      IMPLICIT REAL*8 (A-H,O-Z)
C THE FIT TO THE EF is described in \public_html\fittery\nlfit\Compton      
      PARAMETER(NCON=5)
      DIMENSION CONS(NCON)
      DATA CONS/0.353545834497530409D0,
     2  0.733045485983995507D0,5.847425542065722315D-02,
     3  0D0,4.039450378833601000D-03/
      ANUM=CONS(1)
      ALE=LOG(EGY)
      ZT=ALE    
      DO I=2,3
        ANUM=ANUM+CONS(I)*ZT
        ZT=ZT*ALE
      ENDDO  
      ADEN=1
      ZT=ALE
      DO I=1,2
        ADEN=ADEN+CONS(I+3)*ZT
        ZT=ZT*ALE
      ENDDO
      EFCOMPT=BEXP(ANUM/ADEN)
      RETURN
      END

