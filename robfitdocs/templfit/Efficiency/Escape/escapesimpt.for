      SUBROUTINE XYEFFS(RAT,pRATp4,pRATp5)
      IMPLICIT REAL*8 (A-H,O-Z)
      LOGICAL LDUM1,LEFF,LDUM2,LDUM
      COMMON /TFIT/ADUM(12),EFF(6),BDUM(60),LDUM1(12),LEFF(6),LDUM2(60)
      COMMON/LOGICVALS/LDUM(40)  
c      DATA E511/510.9989d0/!{keV}{in Meyerhof --> 511.006 keV}
      DATA UATT511/9.5812060348407275D0/!MUATT(511)*RHO(32)
      EXP4=EXP(-UATT511*EFF(4))
      EXP5=EXP(-UATT511*EFF(5))
      pEXP4p4=-UATT511*EXP4
      pEXP5p5=-UATT511*EXP5
      SNUM=EXP4+EXP5-EXP4*EXP5
      pSNUMp4=pEXP4p4*(1-EXP5)
      pSNUMp5=pEXP5p5*(1-EXP5)
      DEN=(1-EXP4)*(1-EXP5)
      pDENp4=-pEXP4p4*(1-EXP5)
      pDENp5=-(1-EXP4)*pEXP5p5    
      RAT=SNUM/DEN
      pRATp4=pSNUMp4/DEN-SNUM*pDENP4/DEN**2
      pRATp5=pSNUMp5/DEN-SNUM*pDENP5/DEN**2
      RETURN
      END  
      
      SUBROUTINE XYEFFD(RAT,pRATp4,pRATp5)
      IMPLICIT REAL*8 (A-H,O-Z)
      LOGICAL LDUM1,LEFF,LDUM2,LDUM
      COMMON /TFIT/ADUM(12),EFF(6),BDUM(60),LDUM1(12),LEFF(6),LDUM2(60)
      COMMON/LOGICVALS/LDUM(40)  
c      DATA E511/510.9989d0/!{keV}{in Meyerhof --> 511.006 keV}
      DATA UATT511/9.5812060348407275D0/!MUATT(511)*RHO(32)
c      print*,'0.60...*RHOOFZ(eff(6)',0.60221367D0*RHOOFZ(eff(6))
c      read(*,*)itest
c      if(itest.eq.0)stop
      EXP4=EXP(-UATT511*EFF(4))
      EXP5=EXP(-UATT511*EFF(5))
      pEXP4p4=-UATT511*EXP4
      pEXP5p5=-UATT511*EXP5
      ANUM=EXP4*EXP5 
      pANUMp4=pEXP4p4*EXP5
      pANUMp5=EXP4*pEXP5p5
      DEN=(1-EXP4)*(1-EXP5)
      pDENp4=-pEXP4p4*(1-EXP5)
      pDENp5=-(1-EXP4)*pEXP5p5    
      RAT=ANUM/DEN
      pRATp4=pANUMp4/DEN-ANUM*pDENP4/DEN**2
      pRATp5=pANUMp5/DEN-ANUM*pDENP5/DEN**2
      RETURN
      END
