      FUNCTION EgyToEffSsimP(Egy,PEFF)
      IMPLICIT REAL*8 (A-H,O-Z)
      DIMENSION PEFF(6)
C      LOGICAL LDUM1,LDUM2
      LOGICAL LDUM,LEGY,LRES,LEFF,LATT,LSKEW,LESCAPE,LCAS,LRAN
      COMMON /FITTEDCONS/EgyCal(6),ResCal(6),FITEFF(6),SKEW(6,3),
     2 ATTNEX(8,3),ESCAPE(3),THETACAS,TRAN,LEGY(6),LRES(6),LEFF(6),
     3 LSKEW(6,3),LATT(8,3),LESCAPE(3),LCAS,LRAN
      COMMON /DOUBLE/DUM(8),GEB,DUM2(11)


      COMMON/LOGICVALS/LDUM(40)  
      DATA E511/510.9989d0/!{keV}{in Meyerhof --> 511.006 keV}
      DATA UATT511/9.5812060348407275D0/
      EXP4=EXP(-UATT511*FITeff(4)*GEB)
      EXP5=EXP(-UATT511*FITeff(5)*GEB)
      pEXP4p4=-UATT511*EXP4
      pEXP5p5=-UATT511*EXP5
      SNUM=EXP4+EXP5-EXP4*EXP5
      pSNUMp4=pEXP4p4*(1-EXP5)
      pSNUMp5=pEXP5p5*(1-EXP5)
      DEN=(1-EXP4)*(1-EXP5)
      pDENp4=-pEXP4p4*(1-EXP5)
      pDENp5=-(1-EXP4)*pEXP5p5    
      RAT=SNUM/DEN
      pRATp4=pSNUMp4/DEN-SNUM*pDENP4/DEN**2
      pRATp5=pSNUMp5/DEN-SNUM*pDENP5/DEN**2
      IF(LDUM(28))THEN !PAIRS
        PRIMARYEFF=EGYTOEFF0(EGY+E511)
        DO I=1,3
          PEFF(I)=0
        ENDDO 
        PEFF(4)=PRIMARYEFF*pRATp4
        PEFF(5)=PRIMARYEFF*pRATp5                   
      ELSE  
C        PRIMARYEFF=EGYTOEFF(EGY+E511,PEFF)
        PRIMARYEFF=EGYTOEFF0(EGY)
        DO I=1,3
          PEFF(I)=PEFF(I)*RAT
        ENDDO  
        PEFF(4)=PEFF(4)*RAT+PRIMARYEFF*pRATp4
        PEFF(5)=PEFF(5)*RAT+PRIMARYEFF*pRATp5        
      ENDIF
      EgyToEffSsimP=PRIMARYEFF*RAT      
      RETURN
      END  
      
      FUNCTION EgyToEffDsimP(Egy,PEFF)
      IMPLICIT REAL*8 (A-H,O-Z)
      DIMENSION PEFF(6)
      LOGICAL LDUM,LEGY,LRES,LEFF,LATT,LSKEW,LESCAPE,LCAS,LRAN
      COMMON /FITTEDCONS/EgyCal(6),ResCal(6),FITEFF(6),SKEW(6,3),
     2 ATTNEX(8,3),ESCAPE(3),THETACAS,TRAN,LEGY(6),LRES(6),LEFF(6),
     3 LSKEW(6,3),LATT(8,3),LESCAPE(3),LCAS,LRAN

      COMMON/LOGICVALS/LDUM(40)  
      COMMON /DOUBLE/DUM(8),GEB,DUM2(11)
      
      DATA E511/510.9989d0/!{keV}{in Meyerhof --> 511.006 keV}
      DATA UATT511/9.5812060348407275D0/
      EXP4=EXP(-UATT511*FITeff(4)*GEB)
      EXP5=EXP(-UATT511*FITeff(5)*GEB)
      pEXP4p4=-UATT511*EXP4
      pEXP5p5=-UATT511*EXP5
      ANUM=EXP4*EXP5 
      pANUMp4=pEXP4p4*EXP5
      pANUMp5=EXP4*pEXP5p5
      DEN=(1-EXP4)*(1-EXP5)
      pDENp4=-pEXP4p4*(1-EXP5)
      pDENp5=-(1-EXP4)*pEXP5p5    
      RAT=ANUM/DEN
      pRATp4=pANUMp4/DEN-ANUM*pDENP4/DEN**2
      pRATp5=pANUMp5/DEN-ANUM*pDENP5/DEN**2
      IF(LDUM(28))THEN !PAIRS 
        PRIMARYEFF=EGYTOEFF0(EGY+2*E511)
        DO I=1,3
          PEFF(I)=0
        ENDDO 
        PEFF(4)=PRIMARYEFF*pRATp4
        PEFF(5)=PRIMARYEFF*pRATp5           
      ELSE  
        PRIMARYEFF=EGYTOEFF0(EGY+2*E511)
C        PRIMARYEFF=EGYTOEFF(EGY+2*E511,PEFF)
C        DO I=1,3
C          PEFF(I)=PEFF(I)*RAT
C        ENDDO  
C        PEFF(4)=PEFF(4)*RAT+PRIMARYEFF*pRATp4
C        PEFF(5)=PEFF(5)*RAT+PRIMARYEFF*pRATp5
      ENDIF
      EgyToEffDsimP=PRIMARYEFF*RAT
      RETURN
      END
