      SUBROUTINE MAOPBIN(L,CFILE,STAT)
      CHARACTER*(*) CFILE,STAT
      LOGICAL COMMITQQ
      IDELAY=10
      ITRY=0
      CALL SLEEPQQ(IDELAY)
10    CONTINUE
      IF(ITRY.GT.0)ISTATUS=IBOBSDEL(CFILE)
      ITRY=ITRY+1      
      OPEN(UNIT=L,file=CFILE,form='BINARY',STATUS=STAT,ERR=1197)
      RETURN
1197  CONTINUE
      IF(ITRY.EQ.10*(ITRY/10))PRINT*,' COULD NOT OPEN BINARY FILE= ',
     2 L,ITRY,' ',CFILE
      IF(COMMITQQ(L))GOTO 10
      CALL FLUSH(L)
      CALL SLEEPQQ(IDELAY)
      IF(ITRY.LT.1000)GOTO 10
      PRINT*,'STAT ',STAT
      PRINT*, ' MAOPBIN IN INTELSYS.FOR '
      PRINT*,' MAOPBIN 44 enter s to trace 0 to stop '
      RETURN
