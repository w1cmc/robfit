      LOGICAL FUNCTION LINQUIRE(NAME) 
      CHARACTER*(*)NAME
      LOGICAL EX
      LINQUIRE=.FALSE.
      IF(INDEX(NAME,'.').GT.0)LINQUIRE=.TRUE.
      IF(LINQUIRE)THEN
        INQUIRE(FILE=NAME,EXIST=EX)
        IF(.NOT.EX)LINQUIRE=.FALSE.
      ENDIF
      RETURN
      END  
      
      FUNCTION ANOV(A,B)
      IMPLICIT REAL*8 (A-H,O-Z)
      DATA ANOVT/8.988465674311580D307/
      AT=ABS(A)
      IF(AT.EQ.0D0)THEN
        ANOV=0
        RETURN
      ENDIF  
      BT=ABS(B)
      IF(BT.EQ.0D0)THEN
        ANOV=0
        RETURN
      ENDIF  
      ALT=LOG(AT)
      BLT=LOG(BT)
      IF(ALT+BLT.LT.709)THEN
        ANOV=A*B
      ELSE
        ANOV=ANOVT
        IF((A.LT.0.AND.B.GT.0).OR.(B.LT.0.AND.A.GT.0))ANOV=-ANOV
      ENDIF
      RETURN
      END 
        
