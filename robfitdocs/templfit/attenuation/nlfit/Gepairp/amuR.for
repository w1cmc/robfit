      FUNCTION AMU(E,Z,DAMUDE,DAMUDZ,LVAR)
      IMPLICIT REAL*8 (A-H,O-Z)
      LOGICAL LVAR
      DIMENSION CNUMA(15),CNUMB(15),CDEN(14)
      DIMENSION CENA(5,9),CENADZ(5,9),CENB(5,9),CENBDZ(5,9),CED(5,9),
     2 CEDDZ(5,9),EK(9),ZT(10)
c      DIMENSION XPOLY(2),PF(91),CONS(91),MPPF(64,1)
      SAVE ZT,EK,CENA,CENADZ,CENB,CENBDZ,CED,CEDDZ
      DATA ZT/10*-1D5/
      
      DATA CNUMA/2.325654565282018,-3.193937132128820,
     2 3.294244355361282,1.079801592984363,-1.125347284612036,
     3 -0.2626617535271497,-0.1655068249356604,0.3106897668469135,
     4 -0.3098017787197044,0.2401387199506216,0.6515991737135192D-02,
     5 -0.5992446530373619D-02,-0.1411643997513373D-01,
     6  0.3537838439237518D-01,-0.2788302562368488D-01/
C      DATA CNUMA/0.695727440008255,-0.489672317712314,1.25457099216625,
C     2 12*0D0/ 
        
      DATA CNUMB/1240.62515869535,402.1515015345265,-1510.586974492635,
     2 36.12828093241439,-339.1393364298452,674.8975922153419,
     3 2.031017958340245,-20.76739238466156,94.39565667349463,
     4 -131.1482915206785,0.1523971655169765D-01,-0.4998003019476995,
     5 2.904612657605285,-8.713836177331618,9.400193917718649/
     
C      DATA CNUMB/6.19880008790512,14*0.0/
     
      DATA CDEN/-0.1519946875243152,-0.3640567537041316,
     2 0.1385334815105365,-0.2675315906944128,0.2495921218350431,
     3 -0.8328131178269927D-02,-0.1472964913208572D-01,
     4  0.5503343086903673D-01,-0.4501034214168238D-01,
     5  0.7715812413917100D-04,0.1522079752255873D-02,
     6 -0.2063087849379302D-02,-0.5044611345960580D-03,
     7  0.1426417705218361D-02/
C      DATA CDEN/14*0D0/
C      DO I=1,15
C        CONS(I)=CNUMA(I)
C      ENDDO
C      DO I=1,14
C        CONS(I+15)=CDEN(I)
C      ENDDO
C      XPOLY(1)=E
C      XPOLY(2)=Z
C      CALL POLY(XPOLY,PF,CONS,FA,MPPF,29,2,0)
      IF(Z.LT.-1D4)THEN
        AMU=0
        DAMUDE=0
        DAMUDZ=0
        RETURN
      ENDIF 
      IT=0
      DO I=1,10
        IF(Z.EQ.ZT(I))THEN
          IT=I
          EXIT
        ELSEIF(ZT(I).EQ.-1D5)THEN
          IT=IT+1
          IF(IT.GT.9)IT=1
          ZT(IT)=Z  
          EK(IT)=EKOFZ(Z)
          X=LOG(Z)
C CONSTRUCT THE CE'S
          CENA(1,IT)=CNUMA(1)+X*(CNUMA(3)+X*(CNUMA(6)+X*(CNUMA(10)
     2   +X*CNUMA(15))))
          CENADZ(1,IT)=CNUMA(3)+X*(2*CNUMA(6)+X*(3*CNUMA(10)
     2   +X*4*CNUMA(15)))
          CENB(1,IT)=CNUMB(1)+X*(CNUMB(3)+X*(CNUMB(6)+X*(CNUMB(10)
     2   +X*CNUMB(15))))
          CENBDZ(1,IT)=CNUMB(3)+X*(2*CNUMB(6)+X*(3*CNUMB(10)
     2   +X*4*CNUMB(15)))
          CED(1,IT)=1+X*(CDEN(2)+X*(CDEN(5)+X*(CDEN(9)+X*CDEN(14))))
          CEDDZ(1,IT)=CDEN(2)+X*(2*CDEN(5)+X*(3*CDEN(9)+X*4*CDEN(14)))
     
          CENA(2,IT)=CNUMA(2)+X*(CNUMA(5)+X*(CNUMA(9)+X*CNUMA(14)))
          CENADZ(2,IT)=CNUMA(5)+X*(2*CNUMA(9)+X*3*CNUMA(14))
          CENB(2,IT)=CNUMB(2)+X*(CNUMB(5)+X*(CNUMB(9)+X*CNUMB(14)))
          CENBDZ(2,IT)=CNUMB(5)+X*(2*CNUMB(9)+X*3*CNUMB(14))
          CED(2,IT)=CDEN(1)+X*(CDEN(4)+X*(CDEN(8)+X*CDEN(13)))
          CEDDZ(2,IT)=CDEN(4)+X*(2*CDEN(8)+X*3*CDEN(13))
        
          CENA(3,IT)=CNUMA(4)+X*(CNUMA(8)+X*CNUMA(13))
          CENADZ(3,IT)=CNUMA(8)+2*X*CNUMA(13)
          CENB(3,IT)=CNUMB(4)+X*(CNUMB(8)+X*CNUMB(13))
          CENBDZ(3,IT)=CNUMB(8)+2*X*CNUMB(13)
          CED(3,IT)=CDEN(3)+X*(CDEN(7)+X*CDEN(12))
          CEDDZ(3,IT)=CDEN(7)+2*X*CDEN(12)
        
          CENA(4,IT)=CNUMA(7)+X*CNUMA(12)
          CENADZ(4,IT)=CNUMA(12)
          CENB(4,IT)=CNUMB(7)+X*CNUMB(12)
          CENBDZ(4,IT)=CNUMB(12)
          CED(4,IT)=CDEN(6)+X*CDEN(11)
          CEDDZ(4,IT)=CDEN(11)
        
          CENA(5,IT)=CNUMA(11)
          CENB(5,IT)=CNUMB(11)
          CED(5,IT)=CDEN(10)
          EXIT
        ENDIF
      ENDDO
      Y=LOG(E)
      IF(E.GT.EK(IT))THEN
        ANUM=CENA(1,IT)+Y*(CENA(2,IT)+Y*(CENA(3,IT)+Y*(CENA(4,IT)
     2   +Y*CENA(5,IT))))
        IF(LVAR)THEN
          DNUMDE=CENA(2,IT)+Y*(2*CENA(3,IT)+Y*(3*CENA(4,IT)
     2     +Y*4*CENA(5,IT)))
          DNUMDZ=CENADZ(1,IT)+Y*(CENADZ(2,IT)+Y*(CENADZ(3,IT)
     2     +Y*CENADZ(4,IT)))
        ENDIF  
      ELSE
        ANUM=CENB(1,IT)+Y*(CENB(2,IT)+Y*(CENB(3,IT)+Y*(CENB(4,IT)
     2   +Y*CENB(5,IT))))
        IF(LVAR)THEN
          DNUMDE=CENB(2,IT)+Y*(2*CENB(3,IT)+Y*(3*CENB(4,IT)
     2     +Y*4*CENB(5,IT)))
          DNUMDZ=CENBDZ(1,IT)+Y*(CENBDZ(2,IT)+Y*(CENBDZ(3,IT)
     3     +Y*CENBDZ(4,IT)))
        ENDIF  
      ENDIF
      DEN=CED(1,IT)+Y*(CED(2,IT)+Y*(CED(3,IT)+Y*(CED(4,IT)
     2 +Y*CED(5,IT))))
      AMUT=ANUM/DEN
      AMU=EXP(AMUT)
      DAMUDE=0
      DAMUDZ=0
      IF(LVAR)THEN  
        DENDZ=CEDDZ(1,IT)+Y*(CEDDZ(2,IT)+Y*(CEDDZ(3,IT)
     2   +Y*CEDDZ(4,IT)))
        DENDE=CED(2,IT)+Y*(2*CED(3,IT)+Y*(3*CED(4,IT)
     2   +Y*4*CED(5,IT)))
        DAMUDE=(DNUMDE-AMUT*DENDE)/(DEN*E)
        DAMUDZ=(DNUMDZ-AMUT*DENDZ)/(DEN*Z)
        DAMUDE=AMU*DAMUDE
        DAMUDZ=AMU*DAMUDZ
      ENDIF  
      RETURN
      END    

