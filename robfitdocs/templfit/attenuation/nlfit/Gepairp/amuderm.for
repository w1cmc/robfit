        FUNCTION EXPAMU(EP,ATTEN1,PATT,PE)
        IMPLICIT REAL*8 (A-H,O-Z)
        DIMENSION ATTEN1(*),PATT(6)
        IF(EP.LT.0)THEN
          PE=0
          EXPAMU=0
          DO I=1,6
            PATT(I)=0
          ENDDO
          RETURN
        ENDIF
        ARGSUM=0
        PE=0
        DO I=1,6,2
          D=ATTEN1(I)
          Z=ATTEN1(I+1)
          IF(Z.GT.0)THEN
            RHOE=RHODDZ(Z,DRHODZ)
            AMUT=AMU(EP,Z,DAMUDE,DAMUDZ,.TRUE.)
            ARGSUM=ARGSUM+D*RHOE*AMUT
            PATT(I)=-RHOE*AMUT
            PATT(I+1)=-D*AMUT*DRHODZ-RHOE*D*DAMUDZ
            PE=PE-RHOE*D*DAMUDE
          ELSE IF (Z.LT.0)THEN 
            RHOE=RHODDZ(-Z,DRHODZ)
            AMUT=AMU(EP,-Z,DAMUDE,DAMUDZ,.TRUE.)
            ARGSUM=ARGSUM+LOG(RHOE*AMUT)
            PATT(I)=0
            PATT(I+1)=DRHODZ/RHOE+DAMUDZ/AMUT
            PE=PE-DAMUDE/AMUT
            IF(D*RHOE*AMUT.LT.81)THEN
              AMUEXP=EXP(-D*RHOE*AMUT)
              ARGSUM=ARGSUM-LOG(1-AMUEXP)
              PE=PE+RHOE*AMUT*AMUEXP/(1-AMUEXP)
              PATT(I)=-RHOE*AMUT*AMUEXP/(1-AMUEXP)
              PATT(I+1)=PATT(I+1)+(D*AMUT*DRHODZ+D*RHOE*DAMUDZ)
     2         *AMUEXP/(1-AMUEXP)
            ENDIF
          ENDIF
        ENDDO
        EXPAMU=EXP(-ARGSUM)
        PE=PE*EXPAMU
        DO I=1,6
          PATT(I)=EXPAMU*PATT(I)
        ENDDO  
        RETURN
        END
        

        FUNCTION EK(Z,DEKDZ)
        IMPLICIT REAL*8 (A-H,O-Z)
c The curve has a statistical error of less than 0.05 KeV.  The errors on
c Tl(80) and Bi(83) are + and - 0.12 KeV.  See Nlfit\EkofZ      
        DIMENSION CONSN(4),CONSD(3)
        DATA CONSN/ 0.8004085118672191D-02,0.1633113527307094D-03,
     2   -0.4223372767326372D-05,0.2265957795031611D-07/
        DATA CONSD/0.2834374736285381D-02,-0.2402736923270774D-03,
     2   0.1455896647602572D-05/
       
        ANUM=Z*Z*(CONSN(1)+Z*(CONSN(2)+Z*(CONSN(3)+Z*CONSN(4))))
        DNUM=Z*(2*CONSN(1)+Z*(3*CONSN(2)+Z*(4*CONSN(3)+Z*5*CONSN(4))))
        ADEN=1+Z*(CONSD(1)+Z*(CONSD(2)+Z*CONSD(3)))
        DDEN=CONSD(1)+Z*(2*CONSD(2)+Z*3*CONSD(3))
        EK=ANUM/ADEN
        DEKDZ=(DNUM-EK*DDEN)/ADEN
        RETURN
        END    

      FUNCTION PHOTO(E,Z,DE,DZ)
      IMPLICIT REAL*8 (A-H,O-Z)
      EKT=EK(Z,DEKDZ)
      if(z.lt.0)print*,' z < 0 '
      if(e.lt.0)print*,' e < 0 '
      IF(E.GT.EKT)THEN
        PHOTO=30.3*Z**3.94/(EKT**.5*E**2.5)
        DE=-2.5*PHOTO/E
        DPHDEK=-.5*PHOTO/EKT
        DZ=3.94*PHOTO/Z+DPHDEK*DEKDZ
      ELSE
        PHOTO=1.5*Z**4.30/(EKT**.5*E**2.5)
        DE=-2.5*PHOTO/E
        DPHDEK=-.5*PHOTO/EKT
        DZ=4.30*PHOTO/Z+DPHDEK*DEKDZ
      ENDIF
      RETURN
      END

      FUNCTION AKN(E,DE)
      IMPLICIT REAL*8 (A-H,O-Z)
      DATA RE/2.817939E-13/
      DATA PI/3.141593/
      DATA ANAVOG/6.02252E23/
      ALPHA=E/511.0034
      DALDE=1/511.0034
      AM=(1+ALPHA)/ALPHA**2
      DAMDE=DALDE/ALPHA**2-2*DALDE*AM
      T1=2*(ALPHA+1)/(1+2*ALPHA)
      DT1=2*DALDE/(1+2*ALPHA)-2*DALDE*T1/(1+2*ALPHA)
      T2=LOG(1+2*ALPHA)/ALPHA
      DT2=2*DALDE/((1+2*ALPHA)*ALPHA)-DALDE*T2/ALPHA
      FBRACK=AM*(T1-T2)
      DFBRACK=DAMDE*(T1-T2)+AM*(DT1-DT2)
      T3=LOG(1+2*ALPHA)/(2*ALPHA)
      DT3=2*DALDE/((1+2*ALPHA)*2*ALPHA)-2*T3*DALDE/ALPHA
      T4=(1+3*ALPHA)/(1+2*ALPHA)**2
      DT4=3*DALDE/(1+2*ALPHA)**2-4*T4*DALDE/(1+2*ALPHA)
      AKN=2*PI*RE*RE*(FBRACK+T3-T4)
      DAKN=2*PI*RE*RE*(DFBRACK+DT3-DT4)
      AKN=AKN*ANAVOG
      DE=DAKN*ANAVOG
      RETURN
      END

      FUNCTION PAIRP(E,DE)
      IMPLICIT REAL*8 (A-H,O-Z)
      PARAMETER(NCON=6)
      DIMENSION CONS(NCON)
      DATA CONS/414.9587086567238,8.4068671945480,0.0112424927967248,
     2 0.0028356388001048,6.5689066643701880D-007,
     3 2.9262621230940130D-007/
      X=E-2*511.0034
C DPAIRPDE = DPAIRPDX * DXDE
      IF(X.LE.0)THEN
        F=0
        DF=0
      ELSE
        ANUM=ABS(CONS(1))+CONS(2)*X
        DANUM=CONS(2)
        ADEN=X
        DADEN=1
        XP=X*X
        XPD=X
        KP=1
        DO K=3,NCON-1,2
          ANUM=ANUM+CONS(K)*XP
          DANUM=DANUM+KP*XPD*CONS(K)
          ADEN=ADEN+CONS(K+1)*XP
          DADEN=DADEN+KP*XPD*CONS(K+1)
          XP=XP*X
          XPD=XPD*X
          KP=KP+1
        ENDDO
        IF(ADEN.EQ.0)THEN
          IF(ANUM.GT.0)THEN
            F=0
            DF=0
          ELSE
            F=1E5
            DF=1E5
          ENDIF
        ELSE
          ARG=ANUM/ADEN
          IF(ABS(ARG).LT.82)THEN
            F=EXP(-ARG)
            DARG=DANUM/ADEN-ANUM*DADEN/(ADEN*ADEN)
            DF=F*DARG
          ELSEIF(ARG.GT.82)THEN
            F=0
            DF=0
          ELSE
            F=1E5
            DF=1E15
          ENDIF
        ENDIF
      ENDIF
      PAIRP=F*238.232/(92*92)
      DE=DF*238.232/(92*92)
      RETURN
      END
      
