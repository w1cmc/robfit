      FUNCTION AMUATTE(Egy,Z,DAMUDE)
      IMPLICIT REAL*8 (A-H,O-Z)
      EKT=EKOFZ(Z)
      DELTAE=.7D0
      IF(Egy-DELTAE.LT.EKT.AND.Egy+DELTAE.GT.EKT)THEN
        FAM=AMUATTBK(EGY-DELTAE,Z,DT)
        FAP=AMUATTAK(EGY+DELTAE,Z,DT)  
        DAMUDE=(FAP-FAM)/(2*DELTAE)
        AMUATTE=.5D0*(FAM+FAP)+(Egy-EKT)*DAMUDE
      ELSEIF(Egy.GT.EKT)THEN
        AMUATTE=AMUATTAK(Egy,Z,DAMUDE)
      ELSE
        AMUATTE=AMUATTBK(Egy,Z,DAMUDE)          
      ENDIF
      RETURN
      END


