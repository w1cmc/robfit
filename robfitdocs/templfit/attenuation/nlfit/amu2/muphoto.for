      FUNCTION AMUphoto(Egy,Z,DAMUDE,DAMUDZ)
      IMPLICIT REAL*8 (A-H,O-Z)
      DIMENSION C(29)
      DATA C/2.50189956492010218D0,-3.69138782250706227D0,
     2 4.56163163326537224D0,0.337537467498031020D0,
     3 0.828341194411263447D0,-1.79920941725586334D0,
     4 2.674047541245638305D-02,-0.293166360413446451D0,
     5 0.209975071839341028D0,0.210128726177244510D0,
     6 -5.972637429744385297D-03,2.597130742900289505D-02,
     7 -1.781909219283497511D-02,9.861409722636777653D-03,
     8 -2.481858804300360001D-02,-0.101499245572347495D0,
     9 -0.282463752547235705D0,-5.971245019736304600D-03,
     A  5.762205030358640629D-02,2.135863595067692384D-02,
     B  1.091173683721614086D-03,-5.023701070141566074D-03,
     C  1.964255126143535518D-03,-2.625840212685240648D-03,
     D  9.229111831219276455D-05,1.312370013838021475D-04,
     E -1.971841365128033719D-05,-2.972283460976305965D-04,
     F -5.674665119157219049D-06/
      ALX=LOG(EGY)
      ALY=LOG(Z)
      ALX2=ALX*ALX
      ALXALY=ALX*ALY
      ALY2=ALY*ALY
      ALX3=ALX2*ALX
      ALX2ALY=ALX2*ALY
      ALXALY2=ALX*ALY2
      ALY3=ALY*ALY2
      ALX4=ALX2*ALX2
      ALX3ALY=ALX3*ALY
      ALX2ALY2=ALX2*ALY2
      ALXALY3=ALX*ALY3
      ALY4=ALY2*ALY2
      ANUM=C(1)+C(2)*ALX+C(3)*ALY+
     2 C(4)*ALX2+C(5)*ALXALY+C(6)*ALY2+
     3 C(7)*ALX3+C(8)*ALX2ALY+C(9)*ALXALY2+C(10)*ALY3+
     4 C(11)*ALX4+C(12)*ALX3ALY+C(13)*ALX2ALY2+C(14)*ALXALY3+C(15)*
     5 ALY4 
      DNUMDLX=C(2)+2*C(4)*ALX+C(5)*ALY+3*C(7)*ALX2+2*C(8)*ALXALY+
     2 C(9)*ALY2+4*C(11)*ALX3+3*C(12)*ALX2ALY+2*C(13)*ALXALY2+
     3 C(14)*ALY3 
      DNUMDLY=C(3)+C(5)*ALX+2*C(6)*ALY+C(8)*ALX2+2*C(9)*ALXALY+
     2 3*C(10)*ALY2+C(12)*ALX3+2*C(13)*ALX2ALY+3*C(14)*ALXALY2+
     3 3*C(15)*ALY3 
      ADEN=1+C(16)*ALX+C(17)*ALY+
     2 C(18)*ALX2+C(19)*ALXALY+C(20)*ALY2+
     3 C(21)*ALX3+C(22)*ALX2ALY+C(23)*ALXALY2+C(24)*ALY3+
     4 C(25)*ALX4+C(26)*ALX3ALY+C(27)*ALX2ALY2+C(28)*ALXALY3+C(29)*
     5 ALY4 
      DDENDLX=C(16)+2*C(18)*ALX+C(19)*ALY+3*C(21)*ALX2+2*C(22)*ALXALY+
     2 C(23)*ALY2+4*C(25)*ALX3+3*C(26)*ALX2ALY+2*C(27)*ALXALY2+
     3 C(28)*ALY3 
      DDENDLY=C(17)+C(19)*ALX+2*C(20)*ALY+C(22)*ALX2+2*C(23)*ALXALY+
     2 3*C(24)*ALY2+C(26)*ALX3+2*C(27)*ALX2ALY+3*C(29)*ALXALY2+
     3 3*C(29)*ALY3 
      RAT=ANUM/ADEN
      PRATPLNX=(DNUMDLX-RAT*DDENDLX/ADEN)/ADEN
      PRATPLNY=(DNUMDLY-RAT*DDENDLY/ADEN)/ADEN
      AMUphoto=EXP(RAT)
      DAMUDE=AMUphoto*PRATPLNX/Egy
      DAMUDZ=AMUphoto*PRATPLNY/Z
      RETURN
      END
