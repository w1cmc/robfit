      FUNCTION AMUATTbelE(Egy,Z,DAMUDE)
      IMPLICIT REAL*8 (A-H,O-Z)
      DIMENSION C2(29),C(10)
      SAVE ZL,C
      DATA ZL/-1D0/
      DATA C2/0.531859488014203448D0,-2.41834086081086875D0,
     2  0.648855992999263608D0,0.296423286815243876D0,
     3 -5.123878299203895643D-02,0.973591493430851592D0,
     4  0.139407628028202639D0,-0.678150655187681254D0,
     5  1.06093965611278716D0, -0.797466202099605537D0,
     6  8.379156460580385408D-03,-6.815846000685643647D-02,
     7  0.196149830144323707D0,-0.246349743337925776D0,
     8  0.129845626101583798D0, 0.116231469697907013D0,
     9 -0.869167368697817124D0, 4.966280871860803070D-02,
     A -0.179431026095859360D0, 0.387513398289463364D0,
     B  1.150101943160359484D-02,-5.586614845895008776D-02,
     C  0.106387958551063309D0,-0.104380018429436495D0,
     D  6.726160554713937241D-04,-4.968586817788527560D-03,
     E  1.385895334150213935D-02,-1.875232067075330536D-02,
     F  1.180942060953138511D-02/
    
      IF(Z.NE.ZL)THEN
        CALL CxyToX(C2,C,Z,4)
        ZL=Z
      ENDIF  
      ALX=LOG(EGY)
      ANUM=C(1)+ALX*(C(2)+ALX*(C(3)+ALX*(C(4)+ALX*C(5))))
      ADEN=C(6)+ALX*(C(7)+ALX*(C(8)+ALX*(C(9)+ALX*C(10))))
      DNUMDLX=C(2)+ALX*(2*C(3)+ALX*(3*C(4)+4*ALX*C(5)))
      DDENDLX=C(7)+ALX*(2*C(8)+ALX*(3*C(9)+4*ALX*C(10)))
      RAT=ANUM/ADEN
      PRATPLNX=(DNUMDLX-RAT*DDENDLX/ADEN)/ADEN
      PRATPLNX=(DNUMDLX-RAT*DDENDLX/ADEN)/ADEN
      AMUATTbelE=EXP(RAT)
      DAMUDE=AMUATTbelE*PRATPLNX/Egy
      RETURN
      END
