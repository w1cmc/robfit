      FUNCTION AmuPairpE(Egy,Z,DAMUDE)
      IMPLICIT REAL*8 (A-H,O-Z)
      DIMENSION C2(55),C(14)
      SAVE ZL,C
      DATA ZL/-1D0/
      DATA C2 /  0.00000000000000000d0,   0.556628877458682275d0,
     2   2.28268961130459244d0,   -0.187850897387824748d0, 
     3  -1.12181348798558859d0,   -0.216365054148433201d0, 
     4   2.142667774139857857D-02, 0.221795823903604049d0, 
     5   2.438219463279187037D-02,-1.030648945726011282D-02, 
     6  -9.300836338368551848D-04,-2.164790399654575689D-02, 
     7   7.849232167125754577D-04, 1.653682916421560873D-02,
     8   1.549304419503815726D-04, 6.073028298374372829D-06,
     9   9.826336328090255238D-04, 3.707413466025533481D-04,
     A  -3.884011600979091494D-03, 9.688149222194067054D-04,
     B  -9.764821155450334135D-04, 3.220255512144887850D-07,
     C  -1.545194450951186425D-05,-3.426175093717073529D-05, 
     D   1.996702032575973433D-04,-6.133278162679462902D-05, 
     E   6.896581687867552099D-05, 2.417528363764866487D-05,
     F  -0.578330901992528975d0,   0.181476341959799151d0, 
     G   0.123763753331926561d0,  -8.864978550731320526D-02, 
     H  -7.647850433513056122D-03,-1.240354013103920899D-02, 
     I   1.393472041968179246D-02, 1.393759644387418244D-02,
     J  -1.202701655129553574D-02, 5.981709646350380711D-04,
     K  -8.522229431837231858D-04,-2.969562082851077810D-03, 
     L   2.851392888132110922D-03, 9.972097496615322565D-04,
     M  -1.187022153651866596D-05, 2.503537711253972304D-05,
     N   1.644301100665625841D-04,-1.556722894591972489D-04, 
     O  -2.342441160812047536D-04,-4.350482055681983178D-05, 
     P   4.465861598302604234D-08,-5.419624408787019962D-07, 
     Q  -1.268355534981496804D-06, 1.299730471413543090D-06,
     R   1.058842454136327988D-05, 7.104185484457283137D-06,
     S   3.048055290089772248D-07/
      IF(Egy.LE.1024)THEN
        DAMUDE=0
        AmuPairpE=1d-10
        RETURN
      ENDIF       
      IF(Z.NE.ZL)THEN
        CALL CxyToX(C2,C,Z,6)
        ZL=Z
      ENDIF  
      ALX=LOG(EGY)
      ANUM=C(1)+ALX*(C(2)+ALX*(C(3)+ALX*(C(4)+ALX*(C(5)+ALX*(C(6)+
     2 ALX*C(7))))))
      ADEN=C(8)+ALX*(C(9)+ALX*(C(10)+ALX*(C(11)+ALX*(C(12)+ALX*(C(13)+
     2 ALX*C(14))))))
      DNUMDLX=C(2)+ALX*(2*C(3)+ALX*(3*C(4)+ALX*(4*C(5)+ALX*(5*C(6)+
     2 ALX*6*C(7)))))
      DDENDLX=C(9)+ALX*(2*C(10)+ALX*(3*C(11)+ALX*(4*C(12)+ALX*(5*C(13)+
     2 ALX*6*C(14)))))
      RAT=ANUM/ADEN
      PRATPLNX=(DNUMDLX-RAT*DDENDLX/ADEN)/ADEN
      AmuPairpE=EXP(RAT)
      DAMUDE=AmuPairpE*PRATPLNX/Egy
      AmuPairpE=max(1d-10,AmuPairpE)
      RETURN
      END
