      FUNCTION CholS(X,Y,C,M)
      IMPLICIT REAL*8 (A-H,O-Z)
C C(1)
C +X*C(2)+Y*C(3)
C +X**2*C(4)+X*Y*C(5)+Y**2*C(6)      
      DIMENSION XP(:),YP(:),C((M+1)*(M+2)/2)
      ALLOCATABLE::XP,YP
      ALLOCATE(XP(M+1),YP(M+1))
      XP(1)=1
      YP(1)=1
      DO I=1,M
        XP(I+1)=X*XP(I)
        YP(I+1)=Y*YP(I)
      ENDDO
      CholS=0
      K=0
      DO I=1,M+1
        DO J=1,I
          K=K+1
          CholS=CholS+XP(I+1-J)*YP(J)*C(K)
        ENDDO
      ENDDO    
      DEALLOCATE(XP,YP)   
      RETURN
      END
      
      FUNCTION DCHOLS(X,Y,C,M)
      IMPLICIT REAL*8 (A-H,O-Z)
C 1
C +X*C(1)+Y*C(2)
C +X**2*C(3)+X*Y*C(4)+Y**2*C(5)      
      DIMENSION XP(:),YP(:),C((M+1)*(M+2)/2)
      ALLOCATABLE::XP,YP
      ALLOCATE(XP(M+1),YP(M+1))
      XP(1)=1
      YP(1)=1
      DO I=1,M
        XP(I+1)=X*XP(I)
        YP(I+1)=Y*YP(I)
      ENDDO
      DCHOLS=1
      K=0
      DO I=2,M+1
        DO J=1,I
          K=K+1
          DCHOLS=DCHOLS+XP(I+1-J)*YP(J)*C(K)
        ENDDO
      ENDDO    
      DEALLOCATE(XP,YP)   
      RETURN
      END
      
      FUNCTION pCholSpy(X,Y,C,M)
      IMPLICIT REAL*8 (A-H,O-Z)
C +X*C(2)+C(3)
C +X*C(5)+2*Y*C(6)      
      DIMENSION XP(:),YP(:),C((M+1)*(M+2)/2)
      ALLOCATABLE::XP,YP
      ALLOCATE(XP(M+1),YP(M+1))
      XP(1)=1
      YP(1)=1
      DO I=1,M
        XP(I+1)=X*XP(I)
        YP(I+1)=Y*YP(I)
      ENDDO
      pCholSpy=0
      K=1
      DO I=2,M+1
        K=K+1 
        DO J=2,I
