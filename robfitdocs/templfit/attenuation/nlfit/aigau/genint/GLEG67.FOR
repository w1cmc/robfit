      SUBROUTINE GLEG67(ABEG,AEND,AI,ERR)
      IMPLICIT REAL*8 (A-H,O-Z)
      DIMENSION X6(3),X7(4),A6(3),A7(4)
      DATA SQRPII/0.5641895835477563D0/
      FUNC(X)=SQRPII*EXP(-X*X)
      DATA X6/0.9324695142031520D0,0.6612093864662645D0,
     2 0.2386191860831969D0/
      DATA A6/0.1713244923791703D0,0.3607615730481386D0,
     2 0.4679139345726910D0/
      DATA X7/0.9491079123427585D0,0.7415311855993944D0,
     2 0.4058451513773972D0,0D0/
      DATA A7/0.1294849661688697D0,0.2797053914892767D0,
     2 0.3818300505051189D0,0.4179591836734694D0/
      XMID=(ABEG+AEND)/2
      RAT=(AEND-ABEG)/2
      AI6=0
      AI7=A7(4)*FUNC(XMID)
      DO I=1,3
        XL=XMID-X6(I)*RAT
        XH=XMID+X6(I)*RAT
        AI6=AI6+A6(I)*(FUNC(XL)+FUNC(XH))
        XL=XMID-X7(I)*RAT
        XH=XMID+X7(I)*RAT
        AI7=AI7+A7(I)*(FUNC(XL)+FUNC(XH))
      ENDDO
      AI=(AI6+AI7)*(AEND-ABEG)/4
      ERR=(AI7-AI6)*(AEND-ABEG)/2
      RETURN
      END

