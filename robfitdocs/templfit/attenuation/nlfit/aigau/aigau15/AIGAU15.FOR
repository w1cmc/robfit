      FUNCTION AIGAU(XT)
      IMPLICIT REAL*8 (A-H,O-Z)
      IF(XT.LT.-27)THEN
        AIGAU=0
        RETURN
      ENDIF
      IF(XT.GT.7)THEN
        AIGAU=1
        RETURN
      ENDIF
      Z=-ABS(XT)
      IF(Z.EQ.0)THEN
        AIGAU=0.5D0
        ERT=0
        RETURN
      ENDIF
      IF(Z.LT.-3)THEN
        ALGAU=-Z*Z-LOG(-2*Z)-.5723649429247001D0
        AIGAU=EXP(ALGAU)*GLAGU(Z)
      ELSE
        AIGAU=AIGAUP(Z)
      ENDIF
      IF(XT.GT.0)THEN
        AIGAU=1-AIGAU
      ENDIF
      RETURN
      END

