      FUNCTION AIGAUP(Z)
      IMPLICIT REAL*8 (A-H,O-Z)
      DIMENSION ALGVAL(9)
      DATA ALGVAL/0.110452484992927D-04,0.102687868070607D-03,
     2 0.731358293340571D-03,0.400497116494002D-02,
     3  0.169474267623447D-01,0.558058841491461D-01,
     4  0.144422183173242D+00,0.297941545282589D+00,
     5  0.500000000000000D+00/
      I=(Z+3)*8/3+.5D0+1
      X=(I-1)*3D0/8-3
      CALL GLEG7(X,Z,AI)
      AIGAUP=ALGVAL(I)+AI*0.5641895835477563D0
      RETURN
      END

      SUBROUTINE GLEG7(ABEG,AEND,AI)
      IMPLICIT REAL*8 (A-H,O-Z)
      DIMENSION X7(4),A7(4)
      DATA X7/0.9491079123427585D0,0.7415311855993944D0,
     2 0.4058451513773972D0,0D0/
      DATA A7/0.1294849661688697D0,0.2797053914892767D0,
     2 0.3818300505051189D0,0.4179591836734694D0/
      XMID=(ABEG+AEND)/2
      RAT=(AEND-ABEG)/2
      AI7=A7(4)*EXP(-XMID*XMID)
      DO I=1,3
        XL=XMID-X7(I)*RAT
        XH=XMID+X7(I)*RAT
        AI7=AI7+A7(I)*(EXP(-XL*XL)+EXP(-XH*XH))
      ENDDO
      AI=AI7*(AEND-ABEG)/2
      RETURN
      END

