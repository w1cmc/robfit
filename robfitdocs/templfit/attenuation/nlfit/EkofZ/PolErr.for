      SUBROUTINE POLY(X,PF,CONS,FA,MPPF,NCONS,NX,MP)
      IMPLICIT REAL*8 (A-H,O-Z)
      PARAMETER (IT=63)
      DIMENSION X(NX),PF(*),CONS(*)
      DIMENSION MPPF(IT+1,*),MPFA(IT+1),MPTEMP(IT+1),MPRAD(IT+1)
     2 MPSQRR(IT+1),MPSQRI(IT+1) 
      F=ABS(X(1))
      RAD=CONS(1)+CONS(2)*F
      SQRRAD=SQRT(RAD)
      C3F=CONS(3)*F
      PF(1)=1+C3F/SQRRAD
      PF(2)=F*PF(1)
      PF(3)=2*F*SQRRAD+2*C3F*F
      FA=RAD+2*CONS(3)*F*SQRRAD+C3F*C3F
      IF(MP.GE.3)THEN    
        CALL MPINIT(MPRAD)
        CALL DPLMP(CONS(1),MPRAD)
        CALL DPLMP(CONS(2)*F,MPRAD)  
        CALL MPSQRT(MPRAD,MPSQRR,IFL)
        CALL MPINV(MPSQRR,MPSQRI)
        
        CALL DXMP(C3F,MPSQRI,MPPF(1,1))
        CALL MPPLI(MPPF(1,1),MPPF(1,1),1)
        
        CALL DXMP(F,MPPF(1,1),MPPF(1,2))
        
        CALL DXMP(2*F,MPSQRR,MPPF(1,3))
        CALL DPLMP(2*C3F*F,MPPF(1,3),MPPF(1,3))

        CALL DXMP(CONS(3)*F,MPSQRR,MPFA)
        CALL MPPLMP(MPRAD,MPFA,MPFA)
        CALL DPLMP(C3F*C3F,MPFA,MPFA)
        FA=DPMP(MPFA)
      ENDIF  
      RETURN
      END

