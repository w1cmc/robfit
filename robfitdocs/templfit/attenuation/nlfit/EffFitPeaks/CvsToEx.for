      IMPLICIT REAL*8 (A-H,O-Z)
      CHARACTER*256 NACVS
      CHARACTER*80 CTEMP
      CHARACTER*89 NAEX
      CHARACTER*1 ANS
      NUMARGS=NARGS()
      IF(NUMARGS.GT.2)THEN
        NTEMP=1
        CALL GETARG(NTEMP,NACVS,NSTATUS)
        NTEMP=2
        CALL GETARG(NTEMP,NAEX,NSTATUS)
      ELSE
        PRINT*,' ENTER THE NAME OF THE CVS FILE'
        READ(*,'(A)')NACVS
        IF(NACVS.EQ.'STOP')STOP 'NO NACVS FILE'
        PRINT*,' ENTER THE NAME OF THE EXAMPLE FILE'
        READ(*,'(A)')NAEX
        IF(NAEX.EQ.'STOP')STOP
      ENDIF
      LCVS=LENTRIM(NACVS)
      PRINT*,'NACVS ',NACVS(:LCVS)
      LEX=LENTRIM(NAEX)
      PRINT*,'NAEX ',NAEX(:LEX)
      OPEN(1,FILE=NACVS)
      OPEN(2,FILE=NAEX)
      READ(1,*)
      PRINT*,'BEFORE DO'
      DO I=1,11
        READ(1,'(A80)')CTEMP
        PRINT*,CTEMP
        ITT=INDEX(CTEMP,',')
        READ(CTEMP(ITT+1:),*)EGY,PKAREA,GAMMA,ERR
        EFF=PEAKAREA/GAMMA
        EFFERR=BOB
        WRITE(2,*)EGY,PKAREA,PEAKAREA/GAMMA,PEAKAREA/GAMMA
      ENDDO 
      CLOSE(1)
      CLOSE(2) 
      READ(*,*)ANS
      STOP
      END  
