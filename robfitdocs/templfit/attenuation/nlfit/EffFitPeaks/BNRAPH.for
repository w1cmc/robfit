      FUNCTION BNRAPH(BEGC,ENDC,ALAMDA)
C BNRAPH IS RETURNED AS THE SMALLEST VALUE OF ROBMFU(ALAMBDA)   
C BRACK BEGINS WITH X1=ALAMBDA AND F1 = F(ALAMDA)
C IT RETURNS .TRUE. X2 AND F2(X2) SUCH THAT F1*F2 <= 0 
C OR .FALSE.  X2 AND F2 SUCH THAT ABS(F2(X2)) IS SMALLEST VALUE FOUND  
C IN THE RANGE X2 = EXP(-BEGC) TO EXP(ENDC)  
C IF(BRACK) FNRAF RETURNS X2 AND THE SMALLEST VALUE OF ABS(ROBMFU(X2))
      IMPLICIT REAL*8 (A-H,O-Z)
      LOGICAL LBRACK,BRACK
      DIMENSION B(:)
C      SAVE B,NALLOC
      ALLOCATABLE B
      COMMON /PASS/NW17,NW18,NCONP,NCOND,FRP,CHIP,AJP     
      DATA FACT1,FACT2/1.377D0,1.0377D0/,NTRY/16/
C      DATA NALLOC/0/
C      IF(NALLOC.EQ.0)THEN
        ALLOCATE (B(NCONP))
C        NALLOC=1
C      ENDIF  
      X1=ALAMDA
      F1=ROBMFU(X1,B)
      REWIND(18)
      READ(18)XT,FMIN
      F1=ROBMFU(X1,B)
      IF(ABS(F1).LT.ABS(FMIN))THEN
        FMIN=F1 
        REWIND(18)
        WRITE(18)X1,FMIN
        WRITE(18)AJP,B
      ENDIF  
      LBRACK=BRACK(FACT1,NTRY,BEGC,ENDC,X1,X2,F1,F2)
      IF(LBRACK)THEN
        BNRAPH=FNRAF(X1,F1,X2,F2)
      ELSE
        x1=x2
        f1=f2
        LBRACK=BRACK(FACT2,NTRY,BEGC,ENDC,X1,X2,F1,F2,ROBMFU)
        IF(LBRACK)THEN
          BNRAPH=FNRAF(X1,F1,X2,F2)
        ELSE
          BNRAPH=F2 
        ENDIF    
      ENDIF
      ALAMDA=X2
      DEALLOCATE(B)
      RETURN
      END  

