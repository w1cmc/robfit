      SUBROUTINE NUMDER(I,X,pFA,CONS,DCONS,NV,POLY)
      IMPLICIT REAL*8 (A-H,O-Z)
      DIMENSION CONS(NV),DCONS(NV)
      DIMENSION PFAT(:),X(1)
      ALLOCATABLE PFAT
      ALLOCATE(PFAT(NV))
      CSAVE=CONS(I)
      CONS(I)=CSAVE-DCONS(I)
      PRINT*,'NUMDER BEFORE CALL POLY'
      CALL POLY(X,pFAT,CONS,FM,NV)
      PRINT*,'NUMDER AFTER CALL POLY'
      CONS(I)=CSAVE+DCONS(I)
      CALL POLY(X,pFAT,CONS,FP,NV)
      pFA=(FP-FM)/(2*DCONS(I))
      CONS(I)=CSAVE
      RETURN
      END
      
