        FUNCTION AOFZ(Z)
        IMPLICIT REAL*8 (A-H,O-Z)
c The curve has a statistical error of less than 0.05 KeV.  The errors on
c Tl(80) and Bi(83) are + and - 0.12 KeV.        
        DIMENSION CONSN(10),CONSD(9)
        DATA CONSN/2.142313847860234D0,0.5371429074956555D-01,
     2 -0.1469101834647968D-01,0.1441106131897655D-02,
     3 -0.7011423319785022D-04,0.1948207059210980D-05,
     4 -0.3224113604019469D-07,0.3133745383422241D-09,
     5 -0.1647191753487104D-11,0.3638431124388611D-14/
             
        DATA CONSD/0.4257652833480899D-01,-0.9233231002570485D-06,
     2 -0.8129274607504220D-07,-0.6486551064976203D-07,
     3 -0.4797338008742749D-08,-0.1160062207726442D-09,
     4 -0.5758689495656526D-10,-0.7305289663862233D-12,
     5 -0.3569911987829773D-08/
       
      ZT=Z
      ANUM=0
      DO I=1,10
        ANUM=ANUM+CONSN(I)*ZT
        ZT=ZT*Z
      ENDDO
      ZT=1
      ADEN=1
      DO I=1,9
        ZT=ZT*Z
        ADEN=ADEN+(CONSD(I)**2)*ZT
      ENDDO  
      AOFZ=ANUM/ADEN
      RETURN
      END  
          
        FUNCTION AOFZDER(Z,DAOFZDZ)
        IMPLICIT REAL*8 (A-H,O-Z)
c The curve has a statistical error of less than 0.05 KeV.  The errors on
c Tl(80) and Bi(83) are + and - 0.12 KeV.        
        DIMENSION CONSN(10),CONSD(9)
        DATA CONSN/2.142313847860234D0,0.5371429074956555D-01,
     2 -0.1469101834647968D-01,0.1441106131897655D-02,
     3 -0.7011423319785022D-04,0.1948207059210980D-05,
     4 -0.3224113604019469D-07,0.3133745383422241D-09,
     5 -0.1647191753487104D-11,0.3638431124388611D-14/
             
        DATA CONSD/0.4257652833480899D-01,-0.9233231002570485D-06,
     2 -0.8129274607504220D-07,-0.6486551064976203D-07,
     3 -0.4797338008742749D-08,-0.1160062207726442D-09,
     4 -0.5758689495656526D-10,-0.7305289663862233D-12,
     5 -0.3569911987829773D-08/
       
      ZT=Z
      ANUM=0
      DO I=1,10
        ANUM=ANUM+CONSN(I)*ZT
        ZT=ZT*Z
      ENDDO
      DNUM=0
      ZT=1
      DO I=1,10
        DNUM=DNUM+CONSN(I)*I*ZT
        ZT=ZT*Z
      ENDDO 
      ZT=1
      ADEN=1
      DO I=1,9
        ZT=ZT*Z
        ADEN=ADEN+(CONSD(I)**2)*ZT
      ENDDO
      ZT=1
      DDEN=0
      DO I=1,9
        DDEN=DDEN+I*ZT*CONSD(I)**2
        ZT=ZT*Z
      ENDDO    
      AOFZDER=ANUM/ADEN
      DAOFZDZ=(DNUM-AOFZDER*DDEN)/ADEN
      RETURN
      END  

