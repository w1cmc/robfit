      FUNCTION AMUATTE(Egy,Z)
      IMPLICIT REAL*8 (A-H,O-Z)
      EKT=EKOFZ(Z)
      DELTAE=.7D0
      IF(Egy-DELTAE.LT.EKT.AND.Egy+DELTAE.GT.EKT)THEN
        EGYB=MAX(1D-1,EGY-DELTAE)
        EGYA=EGY+DELTAE
        FAM=AMUATTBKE(EGYB,Z)
        FAP=AMUATTAKE(EGYA,Z)  
        DAMUDE=(FAP-FAM)/(2*(EGYA-EGYB))
        AMUATTE=.5D0*(FAM+FAP)+(Egy-EKT)*DAMUDE
      ELSEIF(Egy.GT.EKT)THEN
        AMUATTE=AMUATTAKE(Egy,Z)
      ELSE
        AMUATTE=AMUATTBKE(Egy,Z)
      ENDIF
      RETURN
      END

