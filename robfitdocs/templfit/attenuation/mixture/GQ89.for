      FUNCTION GQ89(A,B,FUN,ERR)
      IMPLICIT REAL*8(A-H,O-Z)
      DIMENSION X8(4),A8(4),X9(4),A9(5)
      DATA X8/9.602898564975362D-1,7.966664774136267D-1,
     2 5.255324099163290D-1,1.834346424956498D-1/
      DATA A8/1.012285362903763D-1,2.223810344533745D-1,
     2 3.137066458778873D-1,3.626837833783620D-1/
      DATA X9/9.681602395076261D-1,8.360311073266358D-1,
     2 6.133714327005904D-1,3.242534234038089D-1/
      DATA A9/8.127438836157441D-2,1.806481606948574D-1,
     2 2.606106964029355D-1,3.123470770400028D-1,3.302393550012598D-1/
      XMID=(B+A)/2
      RANGE=(B-A)/2
      
      AI=0
      DO I=1,4
        XL=XMID-X8(I)*RANGE
        XA=XMID+X8(I)*RANGE
        AI=AI+A8(I)*(FUN(XL)+FUN(XA))
      ENDDO  
      F8=RANGE*AI
      AI=0
      DO I=1,4
        XL=XMID-X9(I)*RANGE
        XA=XMID+X9(I)*RANGE
        AI=AI+A9(I)*(FUN(XL)+FUN(XA))
      ENDDO  
      AI=AI+A9(5)*FUN(XMID)
      F9=RANGE*AI
      GQ89=(F8+F9)/2
      ERR=ABS(F9-F8)
      RETURN
      END
      
      
