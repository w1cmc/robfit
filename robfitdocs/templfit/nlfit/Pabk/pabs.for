     4 121.7064942107703D0,1362.807311990774D0,-5962.480627235467D0,
     5 4542.286069746695D0,207.8588215473125D0,-1602.133205134600D0,
     6 3600.790107843806D0,-1881.349973085433D0,20.17741635056178D0,
     7 -182.3471343126023D0,698.2779310024108D0,-1070.963985388954D0,
