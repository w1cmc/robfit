     C 2.581797953022914D0,0.3714540501012586D-01/
       
      EKT=EKOFZDER(Z,DEKDZ)
      NCONS=34
      IF(E.GT.EKT)THEN
        IF(LDER)THEN
          CALL PHABSD(CONSA,E,Z,FA,DPDE,DPDZ)
        ELSE
          CALL PHABS(CONSA,E,Z,FA)
        ENDIF    
      ELSE
        IF(LDER)THEN
          CALL PHABSD(CONSB,E,Z,FA,DPDE,DPDZ)
        ELSE
          CALL PHABS(CONSB,E,Z,FA)
        ENDIF    
      ENDIF 
C The derivative is infinite at the K edge.  This wants to be made DeltaP/DeltaE 
C over a range ~ fwhm of the peak involved.  This peak will be have a fwhm ~ 2 KeV 
      IF(LDER)THEN 
        DELTAE=.7D0
        IF(E-DELTAE.LT.EKT.AND.E+DELTAE.GT.EKT)THEN
          CALL PHABS(CONSB,E-DELTAE,Z,FAM)
          CALL PHABS(CONSA,E+DELTAE,Z,FAP)
          DPDE=(FAP-FAM)/(2*DELTAE)
          EKT=EKOFZDER(Z,DEKDZ)
          DPDZ=DPDE*DEKDZ
          FA=.5D0*(FAM+FAP)+(E-EKT)*DPDE
        ENDIF
      ENDIF    
      FA=EXP(FA)
      IF(LDER)THEN
        DPDE=DPDE*FA
        DPDZ=DPDZ*FA
      ENDIF  
      PADEDZ=FA
      RETURN
      END
      
      SUBROUTINE PHABS(CONS,E,Z,FA)
      IMPLICIT REAL*8 (A-H,O-Z)
      DIMENSION CONS(34),ALE(6),ALZ(6),RAT(6)
      ALE(1)=LOG(E)
      ALZ(1)=LOG(Z) 
      DO I=2,6
        ALE(I)=ALE(1)*ALE(I-1)
        ALZ(I)=ALZ(1)*ALZ(I-1)
      ENDDO  
      EI=1/E
      ZI=1/Z  
      FA=CONS(1)
      DPDZ=0
      DPDE=0
      FA=FA+CONS(2)*ALZ(1)+CONS(3)*ALE(1)
      DPDE=DPDE+CONS(3)*EI
      DPDZ=DPDZ+CONS(2)*ZI
      
      RAT(1)=E*ZI*ZI
      RAT(2)=E*E*ZI*ZI
      RAT(3)=E*ZI
      RAT(4)=E*E*ZI
      RAT(5)=E*ZI*ZI*ZI
      RAT(6)=E*E*ZI*ZI*ZI
      ARGL=1
      DO I=4,9
        ARGL=ARGL+CONS(I)*RAT(I-3)
      ENDDO
      FA=FA+LOG(ARGL*ARGL)/2
      
      FA=FA+CONS(10)*ALE(2)+CONS(11)*ALE(1)*ALZ(1)+CONS(12)*ALZ(2)
      
      FA=FA+CONS(13)*ALE(3)+CONS(14)*ALE(2)*ALZ(1)+
     2 CONS(15)*ALE(1)*ALZ(2)+CONS(16)*ALZ(3)
      
      FA=FA+CONS(17)*ALE(4)+CONS(18)*ALE(3)*ALZ(1)+
     2 CONS(19)*ALE(2)*ALZ(2)+CONS(20)*ALE(1)*ALZ(3)+CONS(21)*ALZ(4)
      
      FA=FA+CONS(22)*ALE(5)+CONS(23)*ALE(4)*ALZ(1)+
     2 CONS(24)*ALE(3)*ALZ(2)+CONS(25)*ALE(2)*ALZ(3)+
     3 CONS(26)*ALE(1)*ALZ(4)+CONS(27)*ALZ(5)
      
C NOTE THAT CONS(34) IS NOT IN EXPECTED ORDER
      FA=FA+CONS(34)*ALE(6)+CONS(28)*ALE(5)*ALZ(1)+
     2 CONS(29)*ALE(4)*ALZ(2)+CONS(30)*ALE(3)*ALZ(3)+
     3 CONS(31)*ALE(2)*ALZ(4)+CONS(32)*ALE(1)*ALZ(5)+
     4 CONS(33)*ALZ(6)
     
      RETURN
      END
      
      SUBROUTINE PHABSD(CONS,E,Z,FA,DPDE,DPDZ)
      IMPLICIT REAL*8 (A-H,O-Z)
      DIMENSION CONS(34),ALE(6),ALZ(6),RAT(6),DRDE(6),DRDZ(6)

      ALE(1)=LOG(E)
      ALZ(1)=LOG(Z) 
      DO I=2,6
        ALE(I)=ALE(1)*ALE(I-1)
        ALZ(I)=ALZ(1)*ALZ(I-1)
      ENDDO  
      EI=1/E
      ZI=1/Z  
      FA=CONS(1)
      DPDZ=0
      DPDE=0
      FA=FA+CONS(2)*ALZ(1)+CONS(3)*ALE(1)
      DPDE=DPDE+CONS(3)*EI
      DPDZ=DPDZ+CONS(2)*ZI
      
      RAT(1)=E*ZI*ZI
      DRDE(1)=ZI*ZI
      DRDZ(1)=-2*E*ZI*ZI*ZI
      RAT(2)=E*E*ZI*ZI
      DRDE(2)=2*E*ZI*ZI
      DRDZ(2)=-2*E*E*ZI*ZI*ZI
      RAT(3)=E*ZI
      DRDE(3)=ZI
      DRDZ(3)=-E*ZI*ZI
      RAT(4)=E*E*ZI
      DRDE(4)=2*E*ZI
      DRDZ(4)=-E*E*ZI*ZI
      RAT(5)=E*ZI*ZI*ZI
      DRDE(5)=ZI*ZI*ZI
      DRDZ(5)=-3*E*ZI*ZI*ZI*ZI
      RAT(6)=E*E*ZI*ZI*ZI
      DRDE(6)=2*E*ZI*ZI*ZI
      DRDZ(6)=-3*E*E*ZI*ZI*ZI*ZI
      ARGL=1
      DO I=4,MIN(NCONS,9)
        ARGL=ARGL+CONS(I)*RAT(I-3)
      ENDDO
      DO I=4,MIN(NCONS,9)
        DPDE=DPDE+CONS(I)*DRDE(I-3)/ARGL
        DPDZ=DPDZ+CONS(I)*DRDZ(I-3)/ARGL
      ENDDO  
      FA=FA+LOG(ARGL*ARGL)/2
      
      FA=FA+CONS(10)*ALE(2)+CONS(11)*ALE(1)*ALZ(1)+CONS(12)*ALZ(2)
      DPDE=DPDE+(2*CONS(10)*ALE(1)+CONS(11)*ALZ(1))*EI
      DPDZ=DPDZ+(CONS(11)*ALE(1)+2*CONS(12)*ALZ(1))*ZI
      
      FA=FA+CONS(13)*ALE(3)+CONS(14)*ALE(2)*ALZ(1)+
     2 CONS(15)*ALE(1)*ALZ(2)+CONS(16)*ALZ(3)
      DPDE=DPDE+(3*CONS(13)*ALE(2)+2*CONS(14)*ALE(1)*ALZ(1)+
     2 CONS(15)*ALZ(2))*EI
      DPDZ=DPDZ+(CONS(14)*ALE(2)+2*CONS(15)*ALE(1)*ALZ(1)+
     2 3*CONS(16)*ALZ(2))*ZI 
      
      FA=FA+CONS(17)*ALE(4)+CONS(18)*ALE(3)*ALZ(1)+
     2 CONS(19)*ALE(2)*ALZ(2)+CONS(20)*ALE(1)*ALZ(3)+CONS(21)*ALZ(4)
      DPDE=DPDE+(4*CONS(17)*ALE(3)+3*CONS(18)*ALE(2)*ALZ(1)+
     2 2*CONS(19)*ALE(1)*ALZ(2)+CONS(20)*ALZ(3))*EI
      DPDZ=DPDZ+(CONS(18)*ALE(3)+2*CONS(19)*ALE(2)*ALZ(1)+
     2 3*CONS(20)*ALE(1)*ALZ(2)+4*CONS(21)*ALZ(3))*ZI
      
      FA=FA+CONS(22)*ALE(5)+CONS(23)*ALE(4)*ALZ(1)+
     2 CONS(24)*ALE(3)*ALZ(2)+CONS(25)*ALE(2)*ALZ(3)+
     3 CONS(26)*ALE(1)*ALZ(4)+CONS(27)*ALZ(5)
      DPDE=DPDE+(5*CONS(22)*ALE(4)+4*CONS(23)*ALE(3)*ALZ(1)+
     2 3*CONS(24)*ALE(2)*ALZ(2)+2*CONS(25)*ALE(1)*ALZ(3)+
     3 CONS(26)*ALZ(4))*EI 
      DPDZ=DPDZ+(CONS(23)*ALE(4)+2*CONS(24)*ALE(3)*ALZ(1)+
     2 3*CONS(25)*ALE(2)*ALZ(2)+4*CONS(26)*ALE(1)*ALZ(3)+
     3 5*CONS(27)*ALZ(4))*ZI
      
C NOTE THAT CONS(34) IS NOT IN EXPECTED ORDER
      FA=FA+CONS(34)*ALE(6)+CONS(28)*ALE(5)*ALZ(1)+
     2 CONS(29)*ALE(4)*ALZ(2)+CONS(30)*ALE(3)*ALZ(3)+
     3 CONS(31)*ALE(2)*ALZ(4)+CONS(32)*ALE(1)*ALZ(5)+
     4 CONS(33)*ALZ(6)
      DPDE=DPDE+(6*CONS(34)*ALE(5)+5*CONS(28)*ALE(4)*ALZ(1)+
     2 4*CONS(29)*ALE(3)*ALZ(2)+3*CONS(30)*ALE(2)*ALZ(3)+
     3 2*CONS(31)*ALE(1)*ALZ(4)+CONS(32)*ALZ(5))*EI
      DPDZ=DPDZ+(CONS(28)*ALE(5)+2*CONS(29)*ALE(4)*ALZ(1)+
     2 3*CONS(30)*ALE(3)*ALZ(2)+4*CONS(31)*ALE(2)*ALZ(3)+
     3 5*CONS(32)*ALE(1)*ALZ(4)+6*CONS(33)*ALZ(5))*ZI        
      
      RETURN
