      DATA CONSA/1.865512997224574D0,4.937005873565258D0,
     2 -3.334432836522461D0,-0.9829026971404943D-01,
     3 -0.5911008351829033D-03,0.2174554080469663D-01,
     4  0.6936926822769607D-04,0.7507006455157013D-01,
     5  0.1352384136433933D-02,0.5758716926822010D-01,
