      IMPLICIT REAL*8 (A-H,O-Z)
      REAL*4 DAT
      DIMENSION DAT(:),SDAT(:),EGY(:)
      ALLOCATABLE::DAT,SDAT,EGY      
      CHARACTER*256 NACML,NASP,NADUM,NAREBIN,CTEMP,NASTR,NADIR,
     2 NATEMP,NADUM1 
      LOGICAL LVCONS,EX
      COMMON /TFIT/CONS(78),LVCONS(78)
      COMMON /NAMES/NACML,NADUM1,NASP,NADUM(3)
      COMMON /INTVALS/IBEGC,IENDC,IDUM(18)
      NASP='NONE'
      NACML='NONE'
      NUMARGS=NARGS()
      IF(NUMARGS.EQ.1)THEN
        PRINT*,' ENTER NACML or NASP'
        READ(*,'(A)')NACML
      ELSEIF(NUMARGS.GE.2)THEN
        NTEMP=1
        CALL BGETARG(NTEMP,NACML)
        IF(NUMARGS.GT.2)THEN
          NTEMP=2
          CALL BGETARG(NTEMP,CTEMP)
          READ(CTEMP,*)DEDC
        ELSE
          PRINT*,' ENTER THE REBINNED DEDC '
          READ(*,*)DEDC  
        ENDIF
      ENDIF
      ILCML=ILB(NACML)
      IF(MAX(INDEX(NACML,'.n42'),INDEX(NACML,'.N42')).GT.1)THEN
        NASP=NACML
        NACML='NONE'
      ENDIF
      IF(MAX(INDEX(NACML,'.sp'),INDEX(NACML,'.SP')).GT.1)THEN
        NASP=NACML
        NACML='NONE'
      ENDIF 
      ILSP=ILB(NASP)  
      NATEMP=NADIR(ILdir) 
      ILTEMP=ILB(NATEMP)
      IF(NACML.EQ.'NONE')THEN
        CTEMP=NASTR('Rfit.txt',ILRFIT,EX) 
        NACML=NATEMP(:ILdir)//CTEMP(:ILRFIT) 
        ILCML=ILdir+ILRFIT
      ENDIF  
      IF(MAX(INDEX(NASP,'.n42'),INDEX(NASP,'.N42')).LT.1.AND.
     2 NACML.EQ.'NONE')THEN
        PRINT*,'STOPPING BECAUSE THERE IS NO CALIBRATION'
        READ(*,'(A)')ANS
        STOP
      ENDIF
      ILSP=ILB(NASP)
      CTEMP=NASTR('RB.sp',ILRBSP,EX) 
      NAREBIN=NATEMP(:ILdir)//CTEMP(:ILRbSP)
      IREBIN=ILB(NAREBIN)
      CALL RDATA() ! READS FROM NACML or NASP FINDS IENDC
      IENDT=IENDC
      CALL RCONS() ! SETS DEFAULT IBEG'S AND IEND'S, MAY CHANGE IENDC 
      IENDC=IENDT
      
      NATEMP=NASTR('DAT.UNF',ILTEMP,EX)
      OPEN(1,FILE=NATEMP,FORM='UNFORMATTED')
      READ(1)IENDC
      ALLOCATE(DAT(IENDC),SDAT(IENDC+1),Egy(IENDC+1))
      READ(1)(DAT(I),I=1,IENDC)
      CLOSE(1)
      SDAT(1)=0
      EGY(1)=CHNTOEGY(1-0.5D0)
      DO I=1,IENDC
        SDAT(I+1)=SDAT(I)+DAT(I)
        EGY(I+1)=CHNTOEGY(I+0.5D0)
      ENDDO 
      IF(SDAT(IENDC).GT.1E16)THEN
        PRINT*,'SDAT IS TOO LARGE FOR THIS METHOD'
        STOP
      ENDIF  
      NDAT=EGY(IENDC+1)/DEDC
      DEALLOCATE(DAT)
      ALLOCATE(DAT(NDAT))
      SDATB=0
      DO I=1,NDAT
        EGYT=DEDC*(I+0.5D0)
        CALL LOCATE(EGYT,EGY,IENDC,J)
C RETURNS A VALUE J SUCH THAT EGY(J)<=EGYT<=EGY(J+1)      
        SDATE=SDAT(J)+(EGYT-EGY(J))*(SDAT(J+1)-SDAT(J))/
     2   (EGY(J+1)-EGY(J))
        DAT(I)=SDATE-SDATB
        SDATB=SDATE
      ENDDO 
      DEALLOCATE(EGY,SDAT)
      
      OPEN(1,FILE=NAREBIN)
      WRITE(1,*)' REBINNED DATA WITH DEDC ='
      WRITE(1,*)DEDC
      WRITE(1,*)' '
      WRITE(1,'(A,1P,E13.5,A)')'Energy calibration: 0.0',DEDC,' 0 0 0 0'
      WRITE(1,*)'REAL,',NDAT      
      CALL COMPOUTR4(1,DAT,NDAT) 
      CLOSE(1)
      STOP
      END

      

