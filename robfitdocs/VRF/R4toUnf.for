      SUBROUTINE R4TOUNF(IL,NADAT,IBNDAT)
      REAL*4 RBIN(:)
      ALLOCATABLE RBIN      
      CHARACTER*1 CTEST(25)
      CHARACTER*25 CTEMP
      CHARACTER*256 NADAT
      EQUIVALENCE (CTEST(1),CTEMP)
      OPEN(3,FILE=NADAT,FORM='UNFORMATTED')
      ALLOCATE(RBIN(IBNDAT))      
      WRITE(3)IBNDAT
      DO I=1,IBNDAT
        DO IS=1,25
          READ(IL)CTEST(IS)
          IF(CTEST(IS).EQ.' '.AND.IS.GT.1)EXIT
        ENDDO
        READ(CTEMP,*)RBIN(I) 
c        IF(I.EQ.49)PRINT*,'RBIN',RBIN
c        IF(I.EQ.16383)PRINT*,'RBIN',RBIN
      ENDDO
      WRITE(3)(RBIN(I),I=1,IBNDAT)
      CLOSE(3)
      DEALLOCATE(RBIN)
      RETURN
      END

