      SUBROUTINE CMLREP(CFLAG,FILEIN,FINSERT)
      CHARACTER*(*) CFLAG,FILEIN,FINSERT
      CHARACTER*250 CTEMP
      LF=INDEX(CFLAG,'  ')-1
      IF(LF.LE.0)LF=LEN(CFLAG)
      LFIN=INDEX(FILEIN,'  ')-1
      IF(LFIN.LE.0)LFIN=LEN(FILEIN)
      LFINS=INDEX(FINSERT,'  ')-1
      IF(LFINS.LE.0)LFINS=LEN(FINSERT)
      CTEMP='cmlrepsa'//' '//CFLAG(2:LF-1)//' '//FILEIN(:LFIN)//' '//
     2 FINSERT(:LFINS)
      LTEMP=9+LF+LFIN+1+LFINS
      IF(LTEMP.GT.250)THEN
        PRINT*,' NAMES TOO LONG FOR WATFOR '
        STOP 37
      ENDIF 
      PRINT*,' CTEMP ',CTEMP(:LTEMP)
      CALL FSYSTEM(CTEMP(:LTEMP)) 
      RETURN
      END

