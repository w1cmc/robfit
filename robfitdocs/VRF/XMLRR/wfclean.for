      SUBROUTINE FILECLEAN(FILEIN)
      CHARACTER*(*) FILEIN
      CHARACTER*250 CTEMP
      LFIN=INDEX(FILEIN,'  ')-1
      IF(LFIN.LE.0)LFIN=LEN(FILEIN)
      CTEMP='fileclean'//' '//FILEIN(:LFIN)
      LTEMP=10+LFIN
      IF(LTEMP.GT.250)THEN
        PRINT*,' NAME IS TOO LONG FOR WATFOR ',CTEMP
        STOP 37
      ENDIF  
      PRINT*,' CTEMP ',CTEMP(:LTEMP)
      CALL FSYSTEM(CTEMP(:LTEMP)) 
      RETURN
      END

