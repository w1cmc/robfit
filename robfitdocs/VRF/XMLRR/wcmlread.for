      SUBROUTINE CMLREAD(CFLAG,FILEIN,FILEOUT,IBNDAT)
      CHARACTER*(*) CFLAG,FILEIN,FILEOUT
      CHARACTER*64 CTEMP
      OPEN(1,FILE='CMLRDSA.IN')
      WRITE(1,'(A)')CFLAG
      WRITE(1,'(A)')FILEIN
      WRITE(1,'(A)')FILEOUT
      CLOSE(1)
      CALL FSYSTEM('CMLRDSA.EXE')
      OPEN(1,FILE='CMLRDSA.IN')
      READ(1,*)IBNDAT
      CLOSE(1)
      RETURN
      END
