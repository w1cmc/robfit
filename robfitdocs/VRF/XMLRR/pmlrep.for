      SUBROUTINE PMLREP(CFLAG,FILEIN,FINSERT)
      IMPLICIT REAL*8 (A-H,O-Z)
C      INTEGER FSYSTEM
      CHARACTER*(*) CFLAG,FILEIN,FINSERT
      CHARACTER*12 FILEOUT
      CHARACTER*512 CTEMP,CFLT
      LOGICAL LEND,LEND2
      DATA FILEOUT/'REP1TEMP.TXT'/
      open(1,file=fileout)
      write(1,*)' '
      close(1)
      
c unit 1 --> unit2 + unit 3 + unit 2   
C *** FIRST DEFINE CFLT   
      LF=LENTRIM(CFLAG)
      IF(LF.LE.0.OR.LF.GT.256)LF=MIN(256,LEN(CFLAG))
      LENCF=0
      DO I=1,LF
        CFLT(I:I)=CFLAG(I:I)
        IF(CFLT(I:I).EQ.'>')THEN
          LENCF=I
          EXIT
        ENDIF
      ENDDO
      IF(LENCF.EQ.0)THEN
        PRINT*,' CFLAG DOES NOT END WITH > ',CFLAG
        READ(*,*)ITEST
        IF(ITEST.EQ.0)STOP
      ENDIF
      CALL MAOPBIN(1,FILEIN,'OLD')
C      PRINT*,'FILEIN ',FILEIN(:LENTRIM(FILEIN))
C      OPEN(1,FILE=FILEIN,STATUS='OLD')
C      PRINT*,'MAOPBIN(1  ',FILEIN(:LENTRIM(FILEIN))
C      PRINT*,'FILEOUT ',FILEOUT(:LENTRIM(FILEOUT))
C      OPEN(2,FILE=FILEOUT)     
      CALL MAOPBIN(2,FILEOUT,'UNKNOWN')
C      PRINT*,'MAOPBIN(2 ',FILEOUT(:LENTRIM(FILEOUT))
          
C COPY UNIT 1 (filein) TO UNIT2 (fileout) UP TO CFLT
      CALL PMLCOP(CFLT,1,2,LENCF,LEND)
      PRINT*,'FINSERT ',FINSERT(:LENTRIM(FINSERT))
C      OPEN(3,FILE=FINSERT,STATUS='OLD')
C      PRINT*,'LINQUIRE A ',LINQUIRE(FINSERT)      
      CALL MAOPBIN(3,FINSERT,'OLD')
C      PRINT*,'MAOPBIN(3 ',FINSERT(:LENTRIM(FINSERT))
      IF(.NOT.LEND)THEN
C       INSERT UNIT 3 (finsert) INTO UNIT 2(fileout)
        CALL PMLINS(3,2)
        
C       SKIP THROUGH '<\'\\CFLT(2:LENCF)
        CTEMP='</'//CFLT(2:LENCF)
        LENCF=LENCF+1
        CFLT=CTEMP(:LENCF)
        
        CALL PMLSKP(CFLT,1,LENCF,LEND2)
        
        CALL PMLINS(1,2)
      ELSE  
        REWIND(1)  
        DO I=1,512
          READ(1,END=127)CFLT(1:1)
          print*,cflt
          IF(CFLT(1:1).EQ.'<')EXIT
        ENDDO  
127     CFLT(:2)='</'
        DO I=3,512
          READ(1,END=131,ERR=131)CFLT(I:I)
          IF(CFLT(I:I).EQ.'>')EXIT
        ENDDO 
131     LENCF=I
        REWIND(1)  
        REWIND(2) 
        CALL PMLCOP(CFLT,1,2,LENCF,LEND)
        CALL PMLINS(3,2)
        WRITE(2)CFLT(:LENCF)       
      ENDIF  
      CLOSE(3)
      CALL FLUSH(2)
      CLOSE(2)
      CLOSE(1)
      ILIN=LENTRIM(FILEIN)
      CTEMP='COPY '//FILEOUT//' "'//FILEIN(:ILIN)//'"'
      CALL FSYSTEM(CTEMP)
      CTEMP='DEL "'//FILEOUT//'"'
      CALL FSYSTEM(CTEMP)
      RETURN
      END
      

      SUBROUTINE PMLCOP(CFLT,I1,I2,LENCF,LEND)
C COPIES MATERIAL FROM UNIT I1 TO I2 UNTIL CFLT IS REACHED      
      CHARACTER*1 CTEST(256)
      CHARACTER*512 CFLT,COMP
      LOGICAL LEND
      EQUIVALENCE (CTEST(1),COMP)
      LEND=.FALSE.
5     CONTINUE
        READ(I1,END=250)CTEST(1)
        IF(CTEST(1).NE.'<')THEN
          WRITE(I2)CTEST(1)
        ELSE
          DO I=2,LENCF-1
            READ(I1,END=250)CTEST(I)
            IF(CTEST(I).EQ.'>')THEN
              WRITE(I2)(CTEST(J),J=1,I)
              GOTO 5
            ENDIF
          ENDDO    
          READ(I1,END=250)CTEST(LENCF)
          IF(CFLT(:LENCF).EQ.COMP(:LENCF))RETURN
          WRITE(I2)(CTEST(J),J=1,LENCF)
        ENDIF        
        GOTO 5
250   CONTINUE
      LEND=.TRUE.
      RETURN
      END
      
      SUBROUTINE PMLSKP(CFLT,I1,LENCF,LEND)
C READS FROM UNIT I1 UNTIL CFLT IS REACHED      
      CHARACTER*1 CTEST(512)
      CHARACTER*512 CFLT,COMP
      LOGICAL LEND
      EQUIVALENCE (CTEST(1),COMP)
      LEND=.FALSE.
5     CONTINUE
        READ(I1,END=250)CTEST(1)
        IF(CTEST(1).NE.'<')GOTO 5
        DO I=2,LENCF-1
          READ(I1,END=250)CTEST(I)
          IF(CTEST(I).EQ.'>')GOTO 5
        ENDDO    
        READ(I1,END=250)CTEST(LENCF)
        IF(CFLT(:LENCF).EQ.COMP(:LENCF))RETURN
        GOTO 5        
250   CONTINUE
      LEND=.TRUE.
      RETURN
      END
      
      SUBROUTINE PMLINS(I1,I2)
C READS FROM UNIT I1, WRITES TO I2
      CHARACTER*1 CTEST       
5     CONTINUE
        READ(I1,END=250,ERR=250)CTEST
        WRITE(I2)CTEST
        GOTO 5
250   CONTINUE
      RETURN
      END                    
      
      SUBROUTINE PMLREPTXT(CFLAG,FILEIN,FINSERT)
      IMPLICIT REAL*8 (A-H,O-Z)
C      INTEGER FSYSTEM
      CHARACTER*(*) CFLAG,FILEIN,FINSERT
      CHARACTER*12 FILEOUT
      CHARACTER*512 CTEMP,CFLT
      DATA FILEOUT/'REP1TEMP.TXT'/
      
C FILEIN  --> FILEIN(UP TO CFLAG) + FINSERT + FILEIN(FROM CFLT)   

      ILFLAG=LENTRIM(CFLAG)
      CFLT='</'//CFLAG(2:ILFLAG)
      ILFLT=ILFLAG+1
      OPEN(1,FILE=FILEIN)
      OPEN(2,FILE=FILEOUT)
15    READ(1,'(A)',END=20)CTEMP 
      IF(INDEX(CTEMP,CFLAG(:ILFLAG)).GE.1)GOTO 20
      ILTEMP=LENTRIM(CTEMP)
      IF(ILTEMP.EQ.0)GOTO 15
      WRITE(2,'(A)')CTEMP(:ILTEMP)
      GOTO 15
20    CONTINUE

25    READ(1,'(A)',END=30,ERR=30)CTEMP
      IF(INDEX(CTEMP,CFLT(:ILFLT)).GE.1)GOTO 30
      GOTO 25
30    CONTINUE      
      CLOSE(3)
      OPEN(3,FILE=FINSERT)
35    READ(3,'(A)',END=40)CTEMP
      ILTEMP=LENTRIM(CTEMP)
      IF(ILTEMP.EQ.0)GOTO 35
      WRITE(2,'(A)')CTEMP(:ILTEMP)
      GOTO 35
40    CONTINUE
      CLOSE(3)
            
45    READ(1,'(A)',END=50,ERR=50)CTEMP      
      ILTEMP=LENTRIM(CTEMP)
      IF(ILTEMP.EQ.0)GOTO 45
      WRITE(2,'(A)')CTEMP(:ILTEMP)
      GOTO 45
50    CONTINUE
      CLOSE(1)
C      CALL FLUSH(2)
      CLOSE(2)
      ILIN=LENTRIM(FILEIN)
      CTEMP='COPY '//FILEOUT//' "'//FILEIN(:ILIN)//'"'
      CALL FSYSTEM(CTEMP)
      CTEMP='DEL "'//FILEOUT//'"'
      CALL FSYSTEM(CTEMP)
      RETURN
      END
      
