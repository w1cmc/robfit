      FUNCTION EXPAMU2(EP,IATT,PATT)
      IMPLICIT REAL*8 (A-H,O-Z)      
      DIMENSION PATT(6)
      LOGICAL LEGY,LRES,LEFF,LATT,LSKEW,LESCAPE,LCAS,LRAN,LVD,LVZ
C      COMMON /TFIT/EgyCal(6),ResCal(6),FITeff(6),Attn(6,3),Skew(6,3)
C     2 ,AJUMP(6,3),EscapeDp,EscapeW,EscapeOff,THETADET,THETAT,Esdum,
C     3 LVCONS(NT)
      COMMON /FITTEDCONS/EgyCal(6),ResCal(6),FITEFF(6),SKEW(6,3),
     2 ATTNEX(8,3),ESCAPE(3),THETACAS,TRAN,LEGY(6),LRES(6),LEFF(6),
     3 LSKEW(6,3),LATT(8,3),LESCAPE(3),LCAS,LRAN
      COMMON /ATTCASE/NCASE(3),NM(3),NA(3)
      DATA LVZ,LVD/2*.FALSE./
      IF(EP.LT.1D0)STOP 'LINE 583 muatt EP<0.1'
      IF(IATT.GT.4)STOP 'LINE 584 muatt IATT>4'    
      LVD=.FALSE.
      DO I=1,7,2
        IF(LATT(I,IATT))LVD=.TRUE. 
      ENDDO   
      LVZ=.FALSE.
      DO I=2,8,2
        IF(LATT(I,IATT))LVZ=.TRUE.
      ENDDO
        
      Z1=ATTNEX(2,IATT)
      Z2=ATTNEX(4,IATT)
      Z3=ATTNEX(6,IATT)
      Z4=ATTNEX(8,IATT)
      ARGSUM=0
      IF(Z1.LT.0.AND.Z2.GE.0.AND.Z3.GE.0)
     2 ARGSUM=SATT(EP,Z1,ATTNEX(1,IATT),LATT(2,IATT),PATT(2),
     3 LATT(1,IATT),PATT(1))
     
      IF(Z1.GE.0.AND.Z2.LT.0.AND.Z3.GE.0)
     2 ARGSUM=SATT(EP,Z2,ATTNEX(3,IATT),LATT(4,IATT),PATT(4),
     3 LATT(3,IATT),PATT(3))
     
      IF(Z1.GE.0.AND.Z2.GE.0.AND.Z3.LT.0)
     2 ARGSUM=SATT(EP,Z3,ATTNEX(5,IATT),LATT(6,IATT),PATT(6),
     3 LATT(5,IATT),PATT(5))

      IF(Z1.LT.0.AND.Z2.LT.0.AND.Z3.GE.0)
     2 ARGSUM=SATT2(EP,Z1,ATTNEX(1,IATT),LATT(2,IATT),PATT(2),
     3 LATT(1,IATT),PATT(1),Z2,ATTNEX(3,IATT),LATT(4,IATT),PATT(4),
     4 LATT(3,IATT),PATT(3))
     
      IF(Z1.LT.0.AND.Z2.GE.0.AND.Z3.LT.0)
     2 ARGSUM=SATT2(EP,Z1,ATTNEX(1,IATT),LATT(2,IATT),PATT(2),
     3 LATT(1,IATT),PATT(1),Z3,ATTNEX(5,IATT),LATT(6,IATT),PATT(6),
     4 LATT(5,IATT),PATT(5))
     
      IF(Z1.GE.0.AND.Z2.LT.0.AND.Z3.LT.0)
     2 ARGSUM=SATT2(EP,Z2,ATTNEX(3,IATT),LATT(4,IATT),PATT(4),
     3 LATT(3,IATT),PATT(3),Z3,ATTNEX(5,IATT),LATT(6,IATT),PATT(6),
     4 LATT(5,IATT),PATT(5))
     
      IF(Z1.LT.0.AND.Z2.LT.0.AND.Z3.LT.0)
     2  ARGSUM=SATT3(EP,Z1,ATTNEX(1,IATT),LATT(2,IATT),PATT(2),
     3  LATT(1,IATT),PATT(1),Z2,ATTNEX(3,IATT),LATT(4,IATT),PATT(4),
     4  LATT(3,IATT),PATT(3),Z3,ATTNEX(5,IATT),LATT(6,IATT),PATT(6),
     5  LATT(5,IATT),PATT(5))
      
      DO I=1,6,2
        Drho=ABS(ATTNEX(I,IATT))
        Z=ATTNEX(I+1,IATT)
        IF(Z.GT.0)THEN
          IF(LATT(I+1,IATT))THEN
            AMUT=AMUATT(EP,Z,PAMUPZ)
          ELSE
            AMUT=AMUATTE(EP,Z)
          ENDIF 
          ARGSUM=ARGSUM-Drho*AMUT   
          IF(LATT(I,IATT))THEN
            PATT(I)=-AMUT !LOG DERIVS
            IF(ATTNEX(I,IATT).LT.0)PATT(I)=-PATT(I)
          ENDIF  
          IF(LATT(I+1,IATT))PATT(I+1)=-Drho*PAMUPZ 
        ENDIF
      ENDDO
      EXPAMU2=BEXP(ARGSUM)
      
      DO I=1,6
        PATT(I)=EXPAMU2*PATT(I)
      ENDDO 
      RETURN
      END

