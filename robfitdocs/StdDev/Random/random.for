      FUNCTION RNDMF()
      IMPLICIT REAL*8 (A-H,O-Z)
      RNDMF=RNDMF4()*(1-1D-8)+1D-8*RNDMF4()
      RETURN
      END

      FUNCTION GRNDMF()
      IMPLICIT REAL*8 (A-H,O-Z)
      GRNDMF=-6
      DO J=1,12
        GRNDMF=GRNDMF+RNDMF()
      ENDDO
      RETURN
      END
      
