      SUBROUTINE G3LINK(EOB,EOE,C1,NASPS,PNAOI,VENERGY,LV,VDAT,VTPL,
     2 VFIT,OFIT,VCNM,VPks,VERR2,VRES,VWTH,VEFF,VDCHN,VCNMERR,
     3 VATTN1,VATTN2,VATTN3,VPTPLE,VMDA)

      IMPLICIT REAL*8 (A-H,O-Z)
      CHARACTER*256 NACMLSP,NAMNU,NADATUNF,NASTR
      CHARACTER*256 NASPS(3)
      CHARACTER*256 FFVAR(:)
      CHARACTER*40 FFCOM(:)
CI    ALLOCATABLE FFCOM,FFVAR
      CHARACTER*1 WGT,WSM,CDUM
      DIMENSION IR(20)      
C*************************************************
C
C   DATA TO MAIN ROUTINE DISMAIN -- UNKDIS
C
C*************************************************
C
C   GRAF3 DATA
C
C*************************************************
      LOGICAL VENERGY,LV,VDAT,VTPL,VFIT,VCNM,OFIT,VPks,
     2 VERR2,VRES,VWTH,VEFF,LDUM,VDCHN,VMDA,
     3 VCNMERR,VATTN1,VATTN2,VATTN3,VPTPLE,LINQUIRE,EX
      CHARACTER*16 PNAOI(3)     
C*************************************************

      LOGICAL LEGY,LRES,LEFF,LATT,LSKEW,LESCAPE,LCAS,LRAN
      COMMON /FITTEDCONS/EgyCal(6),ResCal(6),FITEFF(6),SKEW(6,3),
     2 ATTNEX(8,3),ESCAPE(3),THETACAS,TRAN,LEGY(6),LRES(6),LEFF(6),
     3 LSKEW(6,3),LATT(8,3),LESCAPE(3),LCAS,LRAN

      COMMON /NAMES/NACMLSP 
      COMMON /INTVALS/IBEGC,IENDC,IDUM(6),NDATT,IBEGCNM,IENDCNM,
     2 IBEGPKF,IENDPKF,IBEGTPL,IENDTPL,IDUM2(7)
     
      COMMON /DOUBLE/ABEGE,AENDE,DUM,ALPHAW1,ALPHAW2,VMIN,VMAX,DUM1(13)
      COMMON/LOGICVALS/LDUM(40)
      COMMON /CHARVALS/WGT,WSM,CDUM(10)
      COMMON /ATTCONS/RHO(4,3),pRHOpZ(4,3),NR1(3),NR2(3),NR3(3)
      
      NUMARGS=NARGS()
      print*,'numargs',numargs
      CALL BGETARG(1,NACMLSP,NSTATUS) 
      
      CALL UNFTOCOM(EX) ! READ THE COMMON CONSTANTS FILE
      IF(.NOT.EX)STOP 'NO COM.UNF FILE'

      IF(LINQUIRE('XMLDIS.MNU'))THEN
        NAMNU='XMLDIS.MNU'
      ELSE  
        NAMNU='\users\public\robfit\XMLDIS.MNU'
      ENDIF 
       
      PRINT*,'NAMNU(:LENTRIM(NAMNU)) '
      CALL RMNUIRNILT(NAMNU,IR,IRN,ILT)
      ALLOCATE (FFCOM(ILT+3),FFVAR(ILT+3))!ALLOWS ADDING 3 LINES TO MENU
      DO I=1,ILT
        FFCOM(I)=' '
        FFVAR(I)=' '
        READ(17,'(1X,I2,1X,A40,A)')K,FFCOM(K),FFVAR(K)
      ENDDO
      FFVAR(9)=NACMLSP !CAN BE CHAGED IN MENURD
      CALL MENURD(FFCOM,FFVAR,IR,ILT) !CAN CHANGE THE CONSTANTS
      NACMLSP=FFVAR(9)
      NADATUNF=NASTR('DAT.UNF',ILDAT,EX)
      PRINT*,'NADATUNF ',NADATUNF(:ILDAT)
      IF(.NOT.EX)STOP 'G3LINK NO DAT.UNF FILE'
      REWIND 17  
      DO I=1,IRN+1
        WRITE(19,*)IR(I)
      ENDDO
      DO I=1,ILT !ILT IS THE NUMBER OF DATA LINES IN THE MENU
        IWRT=MAX(1,LENTRIM(FFVAR(I)))
        WRITE(17,'(I3,1X,A40,A)')I,FFCOM(I),FFVAR(I)(1:IWRT)
      ENDDO
      CLOSE(17)
      VENERGY=.FALSE.
      IF(INDEX(FFCOM(10),'Energy calibrated').GT.0)VENERGY=.TRUE.
      IF(VENERGY)THEN
        READ(FFVAR(11),*)ABEG,AEND
        IBEGC=EGYTOCHN(ABEG+0.5D0)
        IENDC=EGYTOCHN(AEND+0.5D0)
        READ(FFVAR(12),*)ABEG,AEND
        IBEGC=EGYTOCHN(ABEG+0.5D0)
        IENDC=EGYTOCHN(AEND+0.5D0)
        READ(FFVAR(12),*)ABEG,AEND
        IBEGCNM=EGYTOCHN(ABEG+0.5D0)
        IENDCNM=EGYTOCHN(AEND+0.5D0)
        READ(FFVAR(13),*)ABEG,AEND
        IBEGPKF=EGYTOCHN(ABEG+0.5D0)
        IENDPKF=EGYTOCHN(AEND+0.5D0)
        READ(FFVAR(14),*)ABEG,AEND
        IBEGTPL=EGYTOCHN(ABEG+0.5D0)
        IENDTPL=EGYTOCHN(AEND+0.5D0)       
      ELSE
        READ(FFVAR(11),*)IBEGC,IENDC
        READ(FFVAR(12),*)IBEGCNM,IENDCNM
        READ(FFVAR(13),*)IBEGPKF,IENDPKF
        READ(FFVAR(14),*)IBEGTPL,IENDTPL
        READ(FFVAR(15),*)dum1(4) !SCALE FACTOR
      ENDIF
      READ(FFVAR(16),*)VMIN,VMAX
      LV=.FALSE.
      IT=MAX(INDEX(FFVAR(17),'O'),INDEX(FFVAR(17),'o'))
      IF(IT.GT.0)LV=.TRUE.
      VDAT=.FALSE.
      IF(FFVAR(20)(1:1).EQ.'Y'.OR.FFVAR(20)(1:1).EQ.'y')VDAT=.TRUE.
      VTPL=.FALSE.
      IF(FFVAR(21)(1:1).EQ.'Y'.OR.FFVAR(21)(1:1).EQ.'y')VTPL=.TRUE.
      VFIT=.FALSE.
      IF(FFVAR(22)(1:1).EQ.'Y'.OR.FFVAR(22)(1:1).EQ.'y')VFIT=.TRUE.
      VCNM=.FALSE.
      IF(FFVAR(23)(1:1).EQ.'Y'.OR.FFVAR(23)(1:1).EQ.'y')VCNM=.TRUE.
      VPks=.FALSE.
      IF(FFVAR(24)(1:1).EQ.'Y'.OR.FFVAR(24)(1:1).EQ.'y')VPks=.TRUE.
      VRES=.FALSE.
      IF(FFVAR(25)(1:1).EQ.'Y'.OR.FFVAR(25)(1:1).EQ.'y')VRES=.TRUE.
      VMDA=.FALSE.
      IF(FFVAR(26)(1:1).EQ.'Y'.OR.FFVAR(26)(1:1).EQ.'y')VMDA=.TRUE.      
      DO I=1,3
        PNAOI(I)=FFVAR(I+26)(:16)
      ENDDO
      LDUM(4)=.FALSE.
      IF(FFVAR(32)(1:1).EQ.'Y'.OR.FFVAR(32)(1:1).EQ.'y')LDUM(4)=.TRUE.
      VCnmErr=.FALSE.
      IF(FFVAR(33)(1:1).EQ.'Y'.OR.FFVAR(33)(1:1).EQ.'y')
     2 VCnmErr=.TRUE.                  
      READ(FFVAR(34),*)EOB,EOE,C1
      VWTH=.FALSE.
      IF(FFVAR(35)(1:1).EQ.'Y'.OR.FFVAR(35)(1:1).EQ.'y')VWTH=.TRUE.     
      VEFF=.FALSE.
      IF(FFVAR(36)(1:1).EQ.'Y'.OR.FFVAR(36)(1:1).EQ.'y')VEFF=.TRUE.
      VATTN1=.FALSE.
      IF(FFVAR(37)(1:1).EQ.'Y'.OR.FFVAR(37)(1:1).EQ.'y')VATTN1=.TRUE.
      VATTN2=.FALSE.
      IF(FFVAR(38)(1:1).EQ.'Y'.OR.FFVAR(38)(1:1).EQ.'y')VATTN2=.TRUE.
      VATTN3=.FALSE.
      IF(FFVAR(39)(1:1).EQ.'Y'.OR.FFVAR(39)(1:1).EQ.'y')VATTN3=.TRUE.
      VDCHN=.FALSE.
      IF(FFVAR(40)(1:1).EQ.'Y'.OR.FFVAR(40)(1:1).EQ.'y')VDCHN=.TRUE.
      OFIT=.FALSE.
      IF(FFVAR(41)(1:1).EQ.'Y'.OR.FFVAR(41)(1:1).EQ.'y')OFIT=.TRUE.
      DO I=1,3
        READ(FFVAR(41+I),'(A)')NASPS(I)
      ENDDO  
      READ(FFVAR(47),*)ALPHAW
      READ(FFVAR(48),*)ALPHAW2      
      VERR2=.FALSE.
      IF(FFVAR(49)(1:1).EQ.'Y'.OR.FFVAR(49)(1:1).EQ.'y')VERR2=.TRUE.
      WGT='D'
      IF(MAX(INDEX(FFVAR(50),'E'),INDEX(FFVAR(50),'e')).GT.0)WGT='E'
      WSM='N'
      IF(INDEX(FFVAR(51),'5').GT.0)WSM='5'
      IF(INDEX(FFVAR(51),'17').GT.0)WSM='7'
      IF(MAX(INDEX(FFVAR(51),'H'),INDEX(FFVAR(51),'h')).GT.0)WSM='H'
      VPTPLE=.FALSE.
      IF(FFVAR(52)(1:1).EQ.'Y'.OR.FFVAR(52)(1:1).EQ.'y')VPTPLE=.TRUE.
      DEALLOCATE(FFCOM,FFVAR)
      print*,'g3link LDUM(28) EgyEffPairs ',LDUM(28)
      PRINT*,'g3link LDUM(33) SIMPLIFIED EFF ',LDUM(33)
      IF(.NOT.LDUM(37))call dtodrho
      READ(*,*)ITEST
      IF(ITEST.EQ.0)STOP

      RETURN
      END
      
      SUBROUTINE RMNUIRNILT(NAMNU,IR,IRN,ILT)
      CHARACTER*256 NAMNU
      DIMENSION IR(20)
C IRN IS THE NUMBER OF PAGES IN THE MENU
C ILT IS THE NUMBER OF DATA LINES IN THE MENU
      IRN=0
      ILT=0
      OPEN(17,FILE=NAMNU(:LENTRIM(NAMNU)),STATUS='OLD',ERR=1900)
      DO I=1,20    
        READ(17,*)IR(I)
        IF(IR(I).GE.100) RETURN
        IRN=IRN+1        
        ILT=ILT+IR(I)
      ENDDO
      STOP 'G3LINK no 100 in first 20 lines in file '
1900  STOP 'COULD NOT OPEN NAMNU'      
      END      
