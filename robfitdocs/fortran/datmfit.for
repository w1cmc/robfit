      SUBROUTINE DATMFIT(DATMFITP,IFIT,IBEGP,IENDP)      
      IMPLICIT REAL*8 (A-H,O-Z)
      REAL*4 DATMFITP(IBEGP:IENDP)
      CHARACTER*256 FNAME,NASTR
      CHARACTER*1 WGT,WSM,CFITTYPE,CDUM
c DAT 10      
c DAT-Cnm  20
c DAT-Pks  30
c DAT-Tpl  40
c DAT-Cnm-Pks 50
c DAT-Cnm-Tpl 60
c DAT-Pks-Tpl 70
c DAT-Cnm-Pks-Tpl 80      
      REAL*4 DAT(:)
C      REAL*4 FIT
      LOGICAL EX
      ALLOCATABLE DAT
C      ALLOCATABLE FIT
C      COMMON /INTVALS/IBEGC,IENDC,IDUM(7),IBEGCNM,IENDCNM,
C     2 IBEGPKF,IENDPKF,IBEGTPL,IENDTPL,IDUM3(7) 
      COMMON /CHARVALS/WGT,WSM,CFITTYPE,CDUM(9) 

C *** RETRIEVE DATA 
      FNAME=NASTR('dat.unf',ILDAT,EX)
      OPEN(2,FILE=FNAME(:ILDAT),FORM='UNFORMATTED',STATUS='OLD')
      READ(2)NDAT
      ALLOCATE(DAT(NDAT))
      READ(2)(DAT(I),I=1,NDAT)
      CLOSE(2)
      DO I=IBEGP,0
        DATMFITP(I)=0
      ENDDO
      IB=MAX(1,IBEGP)
      IE=MIN(IENDP,NDAT)
      DO I=IB,IE
        DATMFITP(I)=DAT(I)
      ENDDO
      DEALLOCATE(DAT) 
      DO I=IE+1,IENDP
        DATMFITP(I)=0
      ENDDO 
      GOTO(10,20,30,40,50,60,70,80)IFIT
10    CONTINUE !DATA
      RETURN              
20    CONTINUE !DATA -CNM
       CALL DMFMC(DATMFITP,IBEGP,IENDP,'FittedCnm.unf')
       RETURN
30    CONTINUE !DAT-PKS
      CALL DMFMC(DATMFITP,IBEGP,IENDP,'FittedPks.unf')
      RETURN
40    CONTINUE !DAT - Tpl
      CALL DMFMC(DATMFITP,IBEGP,IENDP,'FittedTpl.unf')
      RETURN
50    CONTINUE !DAT -CNM -PKS
      CALL DMFMC(DATMFITP,IBEGP,IENDP,'FittedCnm.unf')
      CALL DMFMC(DATMFITP,IBEGP,IENDP,'FittedPks.unf')
      RETURN      
60    CONTINUE !DAT - CNM - TPL
      CALL DMFMC(DATMFITP,IBEGP,IENDP,'FittedCnm.unf')
      CALL DMFMC(DATMFITP,IBEGP,IENDP,'FittedTpl.unf')
      RETURN      
70    CONTINUE !DATA-PKS-Tpl
      CALL DMFMC(DATMFITP,IBEGP,IENDP,'FittedPks.unf')
      CALL DMFMC(DATMFITP,IBEGP,IENDP,'FittedTpl.unf')
      RETURN
80    CONTINUE !DATA-CNM-PKS-TPL
      CALL DMFMC(DATMFITP,IBEGP,IENDP,'FittedCnm.unf')
      CALL DMFMC(DATMFITP,IBEGP,IENDP,'FittedPks.unf')
      print*,'datmfit calling with datmfitp'
      CALL DMFMC(DATMFITP,IBEGP,IENDP,'FittedTpl.unf')
      RETURN
      END            

      SUBROUTINE DMFMC(DATMFITP,IBEGP,IENDP,CTYPE)
      IMPLICIT REAL*8 (A-H,O-Z)
      REAL*4 DATMFITP(IBEGP:IENDP)
      REAL*4 FIT(:)
      ALLOCATABLE FIT      
      LOGICAL EX
      CHARACTER*(*)CTYPE
      CHARACTER*256 FNAME,NASTR
      ILC=LENTRIM(CTYPE)
      PRINT*,'CTYPE ',CTYPE(:ILC)
      FNAME=NASTR(CTYPE(:ILC),ILCNM,EX)
      print*,'inside dmfmc fname ',FNAME(:LENTRIM(FNAME))
      IF(.NOT.EX)THEN
        PRINT*,'NO FNAME ',FNAME(:ILCNM)
        PRINT*,'CONTIUING WITHOUT IT'
        RETURN
      ENDIF 
      OPEN(3,FILE=FNAME,FORM='UNFORMATTED')
      READ(3)IBEG,IEND 
      PRINT*,'IBEG,IEND',IBEG,IEND
      ALLOCATE(FIT(IBEG:IEND))
      READ(3)(FIT(I),I=IBEG,IEND)
      CLOSE(3)
      IB=MAX(IBEG,IBEGP)
      IE=MIN(IEND,IENDP)
      DO I=IBEGP,IB-1
        DATMFITP(I)=DATMFITP(I)-FIT(IBEG)
      ENDDO
      DO I=IB,IE 
        DATMFITP(I)=DATMFITP(I)-FIT(I)
      ENDDO 
      DO I=IE+1,IENDP
        DATMFITP(I)=DATMFITP(I)-FIT(IEND)
      ENDDO
      DEALLOCATE(FIT)
      RETURN
      END      
