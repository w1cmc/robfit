
      SUBROUTINE FSYSTEM(STRING)
      USE PORTLIB
      CHARACTER*(*) STRING
      I=SYSTEM(STRING)
      IF(I.EQ.-1)THEN
        ERRNUM=IERRNO()
        PRINT*,' Error ',ERRNUM
      ENDIF
      RETURN
      END


      SUBROUTINE IGETARG(NTEMP,NADIR)
      CHARACTER*(*)NADIR
	INTEGER*2 NGARG,NSTATUS
	NGARG=NTEMP
      CALL GETARG(NGARG,NADIR,NSTATUS)
      RETURN
      END

	FUNCTION IARGC()
	USE MSFLIB 
	IARGC=NARGS()
	RETURN
	END



