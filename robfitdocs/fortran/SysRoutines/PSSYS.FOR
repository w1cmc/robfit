      SUBROUTINE BINOPEN(I,NA)
      CHARACTER*(*) NA
      OPEN(I,FILE=NA,FORM='BINARY',SHARE='DENYNONE')
      RETURN
      END

        SUBROUTINE FSYSTEM(STRING)
        USE PORTLIB
        CHARACTER*(*) STRING
        I=SYSTEM(STRING)
        IF(I.EQ.-1)THEN
          ERRNUM=IERRNO()
          PRINT*,' Error ',ERRNUM
        ENDIF
        RETURN
        END


