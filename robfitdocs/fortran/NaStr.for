      FUNCTION NASTR(CTEMP,ILW,EX)
      CHARACTER*(*)CTEMP
      REAL*8 BINDEX
      CHARACTER*256 NAPMLSP,NASTR
      LOGICAL EX,LINQUIRE
      COMMON /NAMES/NAPMLSP
      ILPML=LENTRIM(NAPMLSP)
      ICASE=0
      IF(MAX(INDEX(NAPMLSP,'.+ml'),INDEX(NAPMLSP,'.+ML')).GT.0)THEN
        ICASE=1
      ELSEIF(MAX(INDEX(NAPMLSP,'.SP'),INDEX(NAPMLSP,'.sp')).GT.0)THEN
        ICASE=2
      ELSEIF(MAX(INDEX(NAPMLSP,'.n42'),INDEX(NAPMLSP,'.N42')).GT.0)THEN
        ICASE=1
      ELSEIF(MAX(INDEX(NAPMLSP,'.PML'),INDEX(NAPMLSP,'.PML')).GT.0)THEN
        ICASE=1
      ELSEIF(INDEX(NAPMLSP,'Rfit.txt').GT.0)THEN 
        ICASE=3 
      ENDIF 
      SELECT CASE(ICASE)
      CASE(1) !three character extension
        IB=BINDEX(NAPMLSP(:ILPML),'\')
        NASTR=NAPMLSP(IB+1:ILPML-4)//CTEMP 
      CASE(2) !two character extension
        IB=BINDEX(NAPMLSP(:ILPML),'\')
        NASTR=NAPMLSP(IB+1:ILPML-3)//CTEMP
      CASE(3) !Rfit.txt extension
        IB=BINDEX(NAPMLSP(:ILPML),'\')
        IB2=INDEX(NAPMLSP,'Rfit.txt')
        IB3=INDEX(NAPMLSP,'.')
        IF(IB2-IB.GT.1)THEN
          NASTR=NAPMLSP(IB+1:IB2-1)//CTEMP
        ELSEIF(IB.GT.0)THEN
          NASTR=NAPMLSP(IB+1:ILPML-4)//CTEMP
        ELSEIF(IB3.GT.0)THEN
          NASTR=NAPMLSP(:IB3-1)//CTEMP  
        ELSE
          NASTR=' '  
        ENDIF 
      CASE DEFAULT  
        NASTR=CTEMP  
      END SELECT 
      ILW=LENTRIM(NASTR)
      EX=LINQUIRE(NASTR(:ILW))
      RETURN    
      END
      
      FUNCTION NAPRE(ILW)
      CHARACTER*256 NAPMLSP,NAPRE
      COMMON /NAMES/NAPMLSP
      NAPRE=' '
      IF(NAPMLSP(:4).EQ.'NONE')THEN
        ILPML=MAX(INDEX(NAPMLSP,'.SP'),INDEX(NAPMLSP,'.sp'),
     2   INDEX(NAPMLSP,'.PML'),INDEX(NAPMLSP,'.PML'),
     3   INDEX(NAPMLSP,'.+ML'),INDEX(NAPMLSP,'.+ml'),
     4   INDEX(NAPMLSP,'Rfit.txt'))
      ENDIF
      IF(ILPML.GT.1)NAPRE=NAPMLSP(:ILPML-1) 
      ILW=LENTRIM(NAPRE)
      RETURN
      END
      
      FUNCTION NADIR(ILW)
      REAL*8 BINDEX
      CHARACTER*256 NAPMLSP,NADIR
      COMMON /NAMES/ NAPMLSP
      NADIR=' '
      ILW=0
      ILPML=LENTRIM(NAPMLSP)
      IB=BINDEX(NAPMLSP(:ILPML),'\')
      IF(IB.GT.0)THEN
        NADIR=NAPMLSP(:IB)
        ILW=LENTRIM(NADIR)
      ENDIF 
      RETURN
      END
      
      FUNCTION NAINDIR(CPASS,ILINDIR)
      CHARACTER*(*)CPASS
      CHARACTER*256 CTEMP,NLEAD,NAINDIR,NADIR,NASTR
      LOGICAL EX
      CTEMP=NASTR(CPASS,ILRFIT,EX) 
      NLEAD=NADIR(ILW) 
      IF(ILW.GT.0)THEN
        NAINDIR=NLEAD(:ILW)//CTEMP(:ILRFIT) !can be the same as naPML
        ILINDIR=ILW+ILRFIT
      ELSE
        NAINDIR=CTEMP(:ILRFIT)
        ILINDIR=ILRFIT        
      ENDIF
      RETURN
      END

