      FUNCTION AIF(XDAT,FDAT,ALPHA,BETA)
      IMPLICIT REAL*8 (A-H,O-Z)
      DIMENSION XDAT(4),FDAT(4)
      DEN(A,B,C,D)=(A-D)*(B-D)*(C-D)
      ANUM(A,B,C,ALPHA,BETA)=A*B*C*(BETA-ALPHA)-(A*B+A*C+B*C)
     2 *(BETA**2-ALPHA**2)/2+(A+B+C)*(BETA**3-ALPHA**3)/3
     3 -(BETA**4-ALPHA**4)/4
      AIF=ANUM(XDAT(2),XDAT(3),XDAT(4),ALPHA,BETA)*FDAT(1)
     2 /DEN(XDAT(2),XDAT(3),XDAT(4),XDAT(1))
     3   +ANUM(XDAT(1),XDAT(3),XDAT(4),ALPHA,BETA)*FDAT(2)
     4 /DEN(XDAT(1),XDAT(3),XDAT(4),XDAT(2))
     5   +ANUM(XDAT(1),XDAT(2),XDAT(4),ALPHA,BETA)*FDAT(3)
     6 /DEN(XDAT(1),XDAT(2),XDAT(4),XDAT(3))
     7   +ANUM(XDAT(1),XDAT(2),XDAT(3),ALPHA,BETA)*FDAT(4)
     8  /DEN(XDAT(1),XDAT(2),XDAT(3),XDAT(4))
      RETURN
      END

