      SUBROUTINE FILETOIFILE4(NAMEIN,NAMEOUT)
      IMPLICIT REAL*8 (A-H,O-Z)
      CHARACTER*(*) NAMEIN,NAMEOUT
C INTEGRATES FI(I)=integral F(I-1) TO F(I) 
      PARAMETER (NDAT=4)      
      DIMENSION XDAT(NDAT),FDAT(NDAT)
      PRINT*,'NAMEIN ',NAMEIN
      OPEN(1,FILE=NAMEIN)
      DO I=1,NDAT
        READ(1,*,END=377)XDAT(I),FDAT(I)
      ENDDO  
      OPEN(2,FILE=NAMEOUT)
      FBEG=AIF(XDAT,FDAT,XDAT(1),XDAT(2))      
      WRITE(2,'(1P,2E24.16)')XDAT(2),FBEG
      PRINT*,'XDAT(2),FBEG',XDAT(2),FBEG
      DO 
        READ(1,*,END=350)XT,FT 
        DO I=1,3
          XDAT(I)=XDAT(I+1)
          FDAT(I)=FDAT(I+1)
        ENDDO 
        XDAT(4)=XT
        FDAT(4)=FT 
        FBEG=FBEG+AIF(XDAT,FDAT,XDAT(2),XDAT(3))
        WRITE(2,'(1P,2E24.16)')XDAT(3),FBEG
        PRINT*,'XDAT(3),FBEG',XDAT(3),FBEG
      ENDDO
350   CONTINUE      
      FINT=FBEG+AIF(XDAT,FDAT,XDAT(3),XDAT(4))
      WRITE(2,'(1P,2E24.16)')XDAT(4),FBEG
      CLOSE(1)
      CLOSE(2)
      RETURN
377   CONTINUE
      STOP 'FEWER THAN 4 DATA POINTS IN INPUT FILE'      
      END  

      FUNCTION BINT(XDAT,FDAT,A,B,JB)
      IMPLICIT REAL*8 (A-H,O-Z)
      PARAMETER (NL=4,NDAT=8)
      DIMENSION X8(4),A8(4),XDAT(NDAT),FDAT(NDAT),ALAG(NL)
      DATA X8/0.960289856497536231D0,0.7966664774136267396D0,
     2 0.525532409916328986D0,0.183434642495649805D0/
      DATA A8/0.101228536290376259D0,0.222381034453374471D0,
     2 0.313706645877887287D0,0.362683783378361983D0/ 
      X(Y,A,B)=((B-A)*Y+(B+A))/2
      AI=0
      DO J=1,NL 
        XM=X(X8(J),A,B)          
        CALL UELAG(NL,JB,XM,ALAG,XDAT)
        FXM=0
        DO I=1,NL
          FXM=FXM+ALAG(I)*FDAT(I+JB)
        ENDDO
        XM2=X(-X8(J),A,B)
        CALL UELAG(NL,JB,XM2,ALAG,XDAT)
        FXM2=0
        DO I=1,NL
          FXM2=FXM2+ALAG(I)*FDAT(I+JB)
        ENDDO
        AI=AI+(FXM+FXM2)*A8(J)
      ENDDO
      BINT=(B-A)*AI/2 
      RETURN
      END       
