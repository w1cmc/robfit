      SUBROUTINE UNFTOCOM(EXCOM)
      IMPLICIT REAL*8 (A-H,O-Z)
      PARAMETER (NT=66)
      CHARACTER*256 FNAME,NASTR
      CHARACTER*8 C4
      CHARACTER*1 CDUM
      LOGICAL LCONS,LDUM,EXCOM
      COMMON /FITTEDCONS/CONS(NT),LCONS(NT)
      COMMON /DOUBLE/DUM(20)
      COMMON /INTVALS/IDUM(22)
      COMMON/LOGICVALS/LDUM(40)
      COMMON /CHARVALS/CDUM(12) 
      COMMON /MOLES/AMOLE(4,3)
      COMMON /C4PASS/C4(10)
      COMMON /ATTCONS/RHO(4,3),pRHOpZ(4,3),NR1(3),NR2(3),NR3(3)       
      FNAME=NASTR('COM.UNF',ILINOUT,EXCOM)
      IF(.NOT.EXCOM)THEN 
        PRINT*,'NO FILE ',FNAME(:LENTRIM(FNAME))
        RETURN
      ENDIF  
      OPEN(2,FILE=FNAME(:ILINOUT),FORM='UNFORMATTED')
      READ(2,ERR=103)CONS,LCONS
      READ(2)DUM
      READ(2)IDUM
C      print*,'unftocom',idum(1),idum(2)
      READ(2)LDUM
      READ(2)CDUM
      READ(2)AMOLE   
      READ(2)C4
      READ(2)RHO,pRHOpZ,NR1,NR2,NR3
      CLOSE(2)     
      RETURN
103   PRINT*,'ERR UNFTOCOM READING ',FNAME(:ILINOUT)
      STOP      
      END
      
      SUBROUTINE COMTOUNF(EX)
      IMPLICIT REAL*8 (A-H,O-Z)
      PARAMETER (NT=66)
      CHARACTER*256 FNAME,NASTR
      CHARACTER*8 C4
      CHARACTER*1 CDUM
      LOGICAL LCONS,LDUM,EX
      COMMON /FITTEDCONS/CONS(NT),LCONS(NT)
      COMMON /DOUBLE/DUM(20)
      COMMON /INTVALS/IDUM(22)
      COMMON/LOGICVALS/LDUM(40)
      COMMON /CHARVALS/CDUM(12)  
      COMMON /MOLES/AMOLE(4,3)      
      COMMON /C4PASS/C4(10)
      COMMON /ATTCONS/RHO(4,3),pRHOpZ(4,3),NR1(3),NR2(3),NR3(3) 
      
      FNAME=NASTR('COM.UNF',ILINOUT,EX)
      OPEN(2,FILE=FNAME(:ILINOUT),FORM='UNFORMATTED')
      EX=.TRUE.
      WRITE(2)CONS,LCONS      
      WRITE(2)DUM
      WRITE(2)IDUM
      WRITE(2)LDUM
      WRITE(2)CDUM 
      WRITE(2)AMOLE
      WRITE(2)C4 
      WRITE(2)RHO,pRHOpZ,NR1,NR2,NR3
      CALL FLUSH(2)  
      CLOSE(2)
      RETURN
      END

