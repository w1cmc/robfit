      IMPLICIT REAL*8 (A-H,O-Z)
      CHARACTER*256 NACML     
      CHARACTER*1 CDUM     
      LOGICAL LDRHO,LD,LDUM,LWT,EX
      REAL*4 WT(:),DATMF(:)
CI    ALLOCATABLE WT,DATMF     
      LOGICAL LEGY,LRES,LEFF,LATT,LSKEW,LESCAPE,LCAS,LRAN

      COMMON /FITTEDCONS/EgyCal(6),ResCal(6),FITEFF(6),SKEW(6,3),
     2 ATTNEX(8,3),ESCAPE(3),THETACAS,TRAN,LEGY(6),LRES(6),LEFF(6),
     3 LSKEW(6,3),LATT(8,3),LESCAPE(3),LCAS,LRAN
    
      COMMON /NAMES/NACML      
      COMMON /INTVALS/IBEGC,IENDC,IDUM(7),IBEGCNM,IENDCNM,
     2 IBEGPKF,IENDPKF,IBEGTPL,IENDTPL,IFIT,IDUM2(5)
      COMMON /DOUBLE/DUM(20)
      COMMON/LOGICVALS/LDUM(40)
      COMMON /CHARVALS/CDUM(12)
      COMMON /MOLES/AMOLE(4,3)
      LD=.TRUE.
      LDRHO=.FALSE.
      CALL CNMLINK(LWT)
      PRINT*,'IBEGCNM:IENDCNM',IBEGCNM,IENDCNM
      ALLOCATE(WT(IBEGCNM:IENDCNM))
      CALL WEIGHT(WT,IBEGCNM,IENDCNM)
      
      ALLOCATE(DATMF(IBEGCNM:IENDCNM))
      CALL DATMFIT(DATMF,8,IBEGCNM,IENDCNM)
      CHISQR=0
      DO I=IBEGCNM,IENDCNM
        RES=DATMF(I)**2*WT(I)
        CHISQR=CHISQR+RES
      ENDDO
      PRINT*,'before fit PLOT CNMRES.OUT CHISQR',CHISQR
      
      
C fit D 1, D-tpl 2, D-tpl-pks 3, D-pks 4
      IF(IFIT.EQ.1)THEN
        CALL DATMFIT(DATMF,1,IBEGCNM,IENDCNM)
      ELSEIF(IFIT.EQ.2)THEN
        CALL DATMFIT(DATMF,4,IBEGCNM,IENDCNM)
      ELSEIF(IFIT.EQ.3)THEN
        CALL DATMFIT(DATMF,7,IBEGCNM,IENDCNM)
      ELSEIF(IFIT.EQ.4)THEN
        CALL DATMFIT(DATMF,3,IBEGCNM,IENDCNM)
      ELSE
        PRINT*,'DO NOT KNOW WHAT TO DO WITH IFIT=',IFIT
        STOP 'BKGFIT 38'      
      ENDIF 
        
      CALL CNMBLI(DATMF,WT,NDAT)
      
      CALL DATMFIT(DATMF,8,IBEGCNM,IENDCNM)
      CHISQR=0
      DO I=IBEGCNM,IENDCNM
        RES=DATMF(I)**2*WT(I)
        CHISQR=CHISQR+RES
      ENDDO
      PRINT*,'AFTER fit PLOT CNMRESA.OUT CHISQR',CHISQR
      
      CALL COMTOUNF(EX)
      END

