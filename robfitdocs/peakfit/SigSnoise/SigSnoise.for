      FUNCTION SIGSNOISE(EGY1,EGY2)
      IMPLICIT REAL*8 (A-H,O-Z)
      CHARACTER*256 FNAME,NASTR
      LOGICAL EX
      REAL*8 CHN(:),AICNM(:),AIDAT(:)
      ALLOCATABLE CHN,AICNM,AIDAT,IB,IE
      SAVE NC,CHN,AICNM,AIDAT,IB,IE
      IF(NC.EQ.0)THEN
        NC=1
        FNAME=NASTR('AIDAT.UNF',ILW,EX)
        OPEN(2,FILE=FNAME,FORM='UNFORMATTED')
        READ(2)IBEGDAT,IENDDAT
        FNAME=NASTR('AICNM.UNF',ILW,EX)
        OPEN(3,FILE=FNAME,FORM='UNFORMATTED')
        READ(3)IBEGCNM,IENDCNM
        IB=MAX(IBEGDAT,IBEGCNM)
        IE=MIN(IENDDAT,IENDCNM)
        ALLOCATE(CHN(IB:IE),AIDAT(IB:IE),AICNM(IB:IE))
        DO I=IBEGDAT,IB-1
          READ(2)DUM1,DUM2
        ENDDO
        DO I=IB,IE
          READ(2)CHN(I),AIDAT(I)
        ENDDO
        CLOSE(2)
        DO I=IBEGCNM,IB-1
          READ(3)DUM1,DUM2
        ENDDO   
        DO I=IB,IE
          READ(3)DUM1,AICNM(I)
        ENDDO
        CLOSE(3)
      ENDIF
      ICHN1=EgyToChn(Egy1)    
      ICHN1=MAX(IB,ICHN1)
      ICHN2=EgyToChn(Egy2)+1
      ICHN2=MIN(IE,ICHN2)
      SIGNAL=AIDAT(ICHN2)-AICNM(ICHN1)-(AIDAT(ICHN1)-AICNM(ICHN1))
      ANOISE=SQRT(AIDAT(ICHN2)-AIDAT(ICHN1))
      SIGSNOISE=SIGNAL/ANOISE
      RETURN
      END        
