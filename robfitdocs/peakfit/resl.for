      SUBROUTINE RESL21A(DAT,PKS,NFPKS,NPKSM,ALR,CLR,NLR,MAXLR) 
      IMPLICIT REAL*8 (A-H,O-Z)
      INCLUDE 'STRUCTURES.FOR'
      COMMON/PKL/IADATMF
      REAL*4 DAT(IBEGPKF:IENDPKF) !data - [templfit] -cnm fit  
      CHARACTER*256 FNAME,NASTR
      LOGICAL EX      
      DIMENSION FDIFF(:),FDAT(:)
      ALLOCATABLE FDIFF,FDAT
      DIMENSION PFA(1),CLR(MAXLR),ALR(MAXLR)
      RECORD /Tpk/Pks(NPKSM) !Structure with current peaks (used by poly)
      COMMON /INTVALS/IDUM(11),IBEGPKF,IENDPKF,IDUM2(7)
c      COMMON /TFIT/DUM(6),RESCAL(6),DUM2(66),LVCONS(78)
      LOGICAL LEGY,LRES,LEFF,LATT,LSKEW,LESCAPE,LCAS,LRAN,LPCAP
      COMMON /FITTEDCONS/EgyCal(6),ResCal(6),FITEFF(6),SKEW(6,3),
     2 ATTNEX(8,3),ESCAPE(3),THETACAS,TRAN,PCAP,LEGY(6),LRES(6),
     3 LEFF(6),LSKEW(6,3),LATT(8,3),LESCAPE(3),LCAS,LRAN,LPCAP

      COMMON/DOUBLE/DUM4(11),CUTOFF,DUM5(8) 
      DIMENSION CHNI(2000),EGYI(2000),ERR(2001)
      EXTERNAL PEAKL
         
      ALLOCATE(FDIFF(IBEGPKF:IENDPKF),FDAT(IBEGPKF:IENDPKF))
      PRINT*,'IN RESL'            
      XTT=IBEGPKF
      FT=0
      IF(NFPKS.GT.0)CALL POLY(XTT,PFA,1,PKS,NFPKS,FT,.FALSE.)
      FDIFF(IBEGPKF)=(DAT(IBEGPKF)-FT)  
C *** FDAT: cumulative data with no peaks removed (PEAKL denominator)
      FDAT(IBEGPKF)=DAT(IBEGPKF)
      DO I=IBEGPKF+1,IENDPKF
        FDAT(I)=FDAT(I-1)+DAT(I)
      ENDDO
      DO I=IBEGPKF+1,IENDPKF
        XTT=I
        FT=0
        IF(NFPKS.GT.0)THEN
          CALL POLY(XTT,PFA,1,PKS,NFPKS,FT,.FALSE.)
        ENDIF  
        FDIFF(I)=FDIFF(I-1)+(DAT(I)-FT)  
      ENDDO
       
      FNAME=NASTR('AIDATMF.unf',ILDAT,EX)
      PRINT*,FNAME(:ILDAT)
      OPEN(2,FILE=FNAME(:ILDAT),FORM='UNFORMATTED')
      WRITE(2)IBEGPKF,IENDPKF
      WRITE(2)(FDIFF(I),I=IBEGPKF,IENDPKF)
      WRITE(2)(FDAT(I),I=IBEGPKF,IENDPKF)
      CLOSE(2)
      PRINT*,'SETTING IADATMF IN COMMON/PKL/ TO 3' 
      IADATMF=3
      TEMP=PEAKL(27D0) !IADATMF=3 UPDATES PEAKL
      DEALLOCATE(FDIFF,FDAT)
      
      CHNI(1)=IBEGPKF
      CHNI(2)=IENDPKF
      NDO=2
      NINT=2000
      CALL BLI(CHNI,EGYI,ERR,NINT,NDO,PEAKL)
      OPEN(2,FILE='SIG.OUT')
      DO I=1,NINT
        WRITE(2,'(1P,2E15.6)')CHNI(I),EGYI(I)
      ENDDO
C FDIFF AND AIDAT ARE TWO FUNCTIONS DEFINED AT CHANNELS IBEGPKF TO IENDPKF 
      INIT=1
      NLR=0
      WPG=10
15    CONTINUE     
      CMAX=CUTOFF
      IEXIT=0
      DO I=1,NINT
        CTEST=EGYI(I)
        IF(CTEST.GE.CMAX)THEN
c          WPG=1.17741*MAX(1D0,ChnToWth(CHNI(I)))
C 1.17741 IS (-2LN(0.5))**.5 DESCRIBED IN CUTOFF AND RESIDUALS.DOC
          DO J=1,NLR
            IF(ABS(CHNI(I)-ALR(J)).LT.10*WPG)CTEST=0
            IF(CTEST.EQ.0)EXIT
          ENDDO
        ENDIF    
        IF(CTEST.GE.CMAX)THEN
          IMAX=I
          CMAX=CTEST 
          WGMAX=WPG
        ENDIF
      ENDDO
      IF(CMAX.GT.CUTOFF.AND.NLR.LT.10)THEN
        NLR=NLR+1
        ALR(NLR)=CHNI(IMAX)
        CLR(NLR)=CMAX
        IF(NLR.LT.10)GOTO 15
      ENDIF 
      RETURN
      END

      FUNCTION PEAKL(X)
      IMPLICIT REAL*8 (A-H,O-Z)
      CHARACTER*256 FNAME,NASTR
      LOGICAL EX
      DIMENSION AIDAT(:),AIDATMF(:)
      ALLOCATABLE AIDAT,AIDATMF      
      COMMON/PKL/IADATMF
      SAVE AIDAT,AIDATMF,IBEG0,IEND0
      WCHN=1.17741*MAX(1D0,ChnToWth(X))
      IF(IADATMF.EQ.3)THEN  
C *** RETRIEVE AIDATMF (cumulative data - peaks) AND AIDAT (cumulative
C *** data), BOTH WRITTEN BY RESL21A FOR THE CURRENT RANGE.  THE RANGE
C *** CAN CHANGE BETWEEN CALLS, SO REALLOCATE WHEN IT DOES.
        FNAME=NASTR('AIDATMF.unf',ILDATMF,EX)
        OPEN(2,FILE=FNAME(:ILDATMF),FORM='UNFORMATTED',STATUS='OLD')
        READ(2)IBEGN,IENDN
        IF(ALLOCATED(AIDATMF))THEN
          IF(IBEGN.NE.IBEG0.OR.IENDN.NE.IEND0)
     2      DEALLOCATE(AIDATMF,AIDAT)
        ENDIF
        IBEG0=IBEGN
        IEND0=IENDN
        IF(.NOT.ALLOCATED(AIDATMF))
     2    ALLOCATE(AIDATMF(IBEG0:IEND0),AIDAT(IBEG0:IEND0))
        READ(2)(AIDATMF(I),I=IBEG0,IEND0)
        READ(2)(AIDAT(I),I=IBEG0,IEND0)
        CLOSE(2)
        IADATMF=1
        PEAKL=0
        RETURN        
      ENDIF
      XUP=X+WCHN    
      IUP=XUP
      IF(IUP.GE.IEND0)THEN
        XUP=IEND0
        IUP=IEND0
        AUNUM=AIDATMF(IUP)
        AUDEN=AIDAT(IUP)
      ELSE
        AUNUM=AIDATMF(IUP)+(AIDATMF(IUP+1)-AIDATMF(IUP))*(XUP-IUP)
        AUDEN=AIDAT(IUP)+(AIDAT(IUP+1)-AIDAT(IUP))*(XUP-IUP)
      ENDIF  
      XDN=X-WCHN
      IDN=XDN
      IF(IDN.LE.IBEG0)THEN
        XDN=IBEG0
        IDN=IBEG0
        ADNUM=AIDATMF(IDN)
        ADDEN=AIDAT(IDN)
      ELSE
        ADNUM=AIDATMF(IDN)+(AIDATMF(IDN+1)-AIDATMF(IDN))*(XDN-IDN)
        ADDEN=AIDAT(IDN)+(AIDAT(IDN+1)-AIDAT(IDN))*(XDN-IDN) 
      ENDIF 
      PEAKL=(AUNUM-ADNUM)/SQRT(MAX(1D0,AUDEN-ADDEN))
      RETURN
      END

